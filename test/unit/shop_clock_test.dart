import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:timezone/data/latest.dart' as tzdata;
import 'package:timezone/timezone.dart' as tz;
import 'package:vinabike_erp/shared/utils/shop_clock_process.dart';
import 'package:vinabike_erp/shared/utils/shop_time.dart';

void main() {
  test('the process runs on the shop clock whatever the device zone', () {
    useShopClockForProcess();
    // A WhatsApp received at 18:59 UTC on 13 October is 15:59 in Chile.
    final received = DateTime.utc(2026, 10, 13, 18, 59);
    expect(received.toLocal().hour, 15);
    expect(received.toLocal().hour, shopTime(received).hour);
    // «Today» starts at the shop's midnight (03:00 UTC in October).
    expect(DateTime(2026, 10, 14).toUtc(), DateTime.utc(2026, 10, 14, 3));
  }, skip: Platform.isWindows);

  test('every surface names and dates a conversation the same way', () {
    final main = File('lib/main.dart').readAsStringSync();
    final body = main.substring(main.indexOf('Future<void> main() async {'));
    // First statement of main: nothing reads the clock before it.
    expect(
      body.indexOf('useShopClockForProcess();'),
      lessThan(body.indexOf('Stopwatch()')),
    );

    final summary =
        File('lib/shared/widgets/notifications_panel.dart').readAsStringSync();
    expect(summary, contains('chat.getChatTitle(conversation)'));
    expect(summary, isNot(contains('_conversationName(')));

    final tile = File('lib/modules/messaging/widgets/conversation_tile.dart')
        .readAsStringSync();
    expect(tile, contains('shopTime(dt)'));
    expect(tile, isNot(contains('dt.toLocal()')));
  });

  test('the shop zone is the package\'s Santiago, carried alone', () {
    tzdata.initializeTimeZones();
    final santiago = tz.getLocation(kShopTimeZone);
    final carried = shopLocation();
    final reason = 'package:timezone changed Chile\'s rules: write this into '
        'packages/vinabike_public_core/lib/shared/utils/shop_zone_data.dart and format it\n'
        '${_shopZoneDataFile(santiago)}';
    expect(carried.transitionAt, santiago.transitionAt, reason: reason);
    expect(carried.transitionZone, santiago.transitionZone, reason: reason);
    expect(carried.zones, santiago.zones, reason: reason);
    // Same answers as the full table on both sides of a change of hour.
    for (final instant in [
      DateTime.utc(2026, 4, 5, 2, 59),
      DateTime.utc(2026, 4, 5, 3, 1),
      DateTime.utc(2026, 9, 6, 3, 59),
      DateTime.utc(2026, 9, 6, 4, 1),
      DateTime.utc(2015, 6, 1, 12),
    ]) {
      expect(
        shopTime(instant),
        tz.TZDateTime.from(instant, santiago),
        reason: '$instant',
      );
    }
  });

  test('nothing new loads the whole world\'s zone table', () {
    // ~0.5 MB of JavaScript each time it reaches a web bundle: the shop's
    // zone comes from shopLocation(). These read a zone the tenant
    // configures, or run on the HTML store's server, and keep the full table.
    const fullTable = {
      'lib/shared/services/employee_self_service_service.dart',
      'lib/modules/worker_portal/pages/worker_home_page.dart',
      'lib/modules/inventory/services/stock_movements_service.dart',
      'lib/modules/hr/services/payroll_voucher_service.dart',
      'packages/vinabike_public_core/lib/public_store/models/portal_time_zone.dart',
      // Santiago only, still to move to shopLocation().
      'lib/modules/settings/pages/user_management_page.dart',
      'lib/modules/ai_assistant/services/ai_attention_read_model.dart',
      'lib/modules/hr/pages/shift_planning_page.dart',
      'lib/modules/hr/pages/attendances_page.dart',
      'lib/modules/hr/widgets/shift_planning_calendar.dart',
    };
    final offenders = [
      for (final root in ['lib', 'packages/vinabike_public_core/lib'])
        for (final file in Directory(root).listSync(recursive: true))
          if (file is File &&
              file.path.endsWith('.dart') &&
              file
                  .readAsStringSync()
                  .contains("import 'package:timezone/data/") &&
              !fullTable.contains(file.path))
            file.path,
    ];
    expect(offenders, isEmpty);
  });
}

String _shopZoneDataFile(tz.Location zone) {
  final b = StringBuffer()
    ..writeln(
      '// Generated by test/unit/shop_clock_test.dart (in the app) from package:timezone',
    )
    ..writeln(
      "// (data/latest.dart): the shop's zone alone, America/Santiago. Do not",
    )
    ..writeln(
      '// edit by hand; when the package brings new rules for Chile that test',
    )
    ..writeln('// fails and prints this file again.')
    ..writeln()
    ..writeln('/// Milliseconds since the epoch at which each period starts.')
    ..writeln('const List<int> shopZoneTransitionAt = [');
  for (final at in zone.transitionAt) {
    b.writeln('  $at,');
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// The index in [shopZonePeriods] each transition switches to.')
    ..writeln('const List<int> shopZoneTransitionZone = [');
  for (var i = 0; i < zone.transitionZone.length; i += 20) {
    final end = i + 20 > zone.transitionZone.length
        ? zone.transitionZone.length
        : i + 20;
    b.writeln('  ${zone.transitionZone.sublist(i, end).join(', ')},');
  }
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// Offset in milliseconds, daylight saving, abbreviation.')
    ..writeln('const List<(int, bool, String)> shopZonePeriods = [');
  for (final period in zone.zones) {
    b.writeln(
      "  (${period.offset}, ${period.isDst}, '${period.abbreviation}'),",
    );
  }
  b.writeln('];');
  return b.toString();
}
