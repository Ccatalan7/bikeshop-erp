  final NumberFormat _numberFormat = NumberFormat('#,##0', 'es_CL');
  final NumberFormat _currencyFormat = ChileanUtils.currencyFormat;
  final TextEditingController _amountController = TextEditingController();
  final TextEditingController _descriptionController = TextEditingController();
  final TextEditingController _referenceController = TextEditingController();
  final TextEditingController _supplierController = TextEditingController();
  final TextEditingController _purchaseInvoiceSearchController =
      TextEditingController();
  final FocusNode _purchaseInvoiceSearchFocusNode = FocusNode();
  final PDFParserService _pdfParserService = PDFParserService();
  final VeryfiProxyService _veryfiProxyService = VeryfiProxyService();

  bool _isExpanded = false;
  bool _isLoading = true;
  bool _isSaving = false;
  bool _isSavingTemplate = false;
  bool _isProcessingOcrFile = false;
  bool _isDraggingOcrFile = false;
  bool _isPurchaseInvoicePickerOpen = false;
  bool _isUpdatingDescription = false;
  bool _descriptionWasAutoGenerated = false;
  String? _loadError;
  String? _bannerMessage;
  String? _lastAutoDescription;
  String? _ocrFileName;
  _QuickExpenseTab _activeTab = _QuickExpenseTab.capture;

  DateTime _expenseDate = DateTime.now();
  ExpenseDocumentType _documentType = ExpenseDocumentType.invoice;
