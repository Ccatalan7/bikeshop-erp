      PurchaseInvoiceStatus.cancelled => Colors.red.shade700,
      PurchaseInvoiceStatus.received => Colors.orange.shade800,
      PurchaseInvoiceStatus.confirmed => Colors.blueGrey.shade700,
      PurchaseInvoiceStatus.sent => Colors.blue.shade700,
      PurchaseInvoiceStatus.draft => Colors.grey.shade700,
    };
  }

