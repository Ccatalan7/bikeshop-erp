  String _fileExtension(String fileName, {String? fallback}) {
    final fallbackText = fallback?.trim().toLowerCase();
    final dotIndex = fileName.lastIndexOf('.');
    if (dotIndex >= 0 && dotIndex < fileName.length - 1) {
      return fileName.substring(dotIndex + 1).toLowerCase();
    }
    return fallbackText ?? '';
  }

  String _inferQuickOcrExtension(Uint8List bytes) {
    if (bytes.length >= 4 &&
        bytes[0] == 0x25 &&
        bytes[1] == 0x50 &&
        bytes[2] == 0x44 &&
        bytes[3] == 0x46) {
      return 'pdf';
    }
    if (bytes.length >= 8 &&
        bytes[0] == 0x89 &&
        bytes[1] == 0x50 &&
        bytes[2] == 0x4E &&
        bytes[3] == 0x47) {
      return 'png';
    }
    if (bytes.length >= 3 &&
        bytes[0] == 0xFF &&
        bytes[1] == 0xD8 &&
        bytes[2] == 0xFF) {
      return 'jpg';
    }
    return '';
  }

  double? _parseOptionalAmount(String? value) {
    if (value == null || value.trim().isEmpty) return null;
    final amount = _parseAmount(value);
    return amount <= 0 ? null : amount;
  }

  DateTime? _parseOptionalDate(String? value) {
    if (value == null || value.trim().isEmpty) return null;
    final match =
        RegExp(r'(\d{1,2})[-/](\d{1,2})[-/](\d{2,4})').firstMatch(value);
    if (match == null) return null;

    var day = int.tryParse(match.group(1)!);
    var month = int.tryParse(match.group(2)!);
    var year = int.tryParse(match.group(3)!);
    if (day == null || month == null || year == null) return null;
    if (month > 12 && day <= 12) {
      final parsedMonth = day;
      day = month;
      month = parsedMonth;
    }
    if (year < 100) year += 2000;
    if (month < 1 || month > 12 || day < 1 || day > 31) return null;
    return DateTime(year, month, day);
  }

