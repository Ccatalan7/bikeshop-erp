  void _togglePurchaseInvoicePicker() {
    setState(() {
      _isPurchaseInvoicePickerOpen = !_isPurchaseInvoicePickerOpen;
      if (_isPurchaseInvoicePickerOpen) {
        _purchaseInvoiceSearchController.clear();
      }
    });

    if (_isPurchaseInvoicePickerOpen) {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (mounted) _purchaseInvoiceSearchFocusNode.requestFocus();
      });
    }
  }

  void _selectPurchaseInvoice(PurchaseInvoice invoice) {
    setState(() {
      _selectedPurchaseInvoice = invoice;
      _isPurchaseInvoicePickerOpen = false;
      _purchaseInvoiceSearchController.clear();
    });
    _applyLinkedInvoiceDescription();
  }

  void _clearPurchaseInvoiceSelection() {
    setState(() {
      _selectedPurchaseInvoice = null;
      _isPurchaseInvoicePickerOpen = false;
      _purchaseInvoiceSearchController.clear();
    });
  }

  String _purchaseInvoiceSearchText(PurchaseInvoice invoice) {
    return _normalizeSearchText(
      [
        _formatPurchaseInvoiceLabel(invoice),
        invoice.invoiceNumber,
        invoice.supplierName ?? '',
        invoice.supplierRut ?? '',
        invoice.status.displayName,
        invoice.total.round().toString(),
        _numberFormat.format(invoice.total.round()),
      ].join(' '),
    ).replaceAll(RegExp(r'[^a-z0-9]+'), ' ');
  }

  Color _purchaseInvoiceStatusColor(PurchaseInvoiceStatus status) {
    return switch (status) {
      PurchaseInvoiceStatus.paid => Colors.green.shade700,
      PurchaseInvoiceStatus.cancelled => Colors.red.shade700,
      PurchaseInvoiceStatus.received => Colors.orange.shade800,
      PurchaseInvoiceStatus.confirmed => Colors.blueGrey.shade700,
      PurchaseInvoiceStatus.sent => Colors.blue.shade700,
      PurchaseInvoiceStatus.draft => Colors.grey.shade700,
    };
  }

  String _formatPurchaseInvoiceLabel(PurchaseInvoice invoice) {
    final supplier = invoice.supplierName ?? 'Proveedor';
    final total = _currencyFormat.format(invoice.total);
    return '${invoice.invoiceNumber} · $supplier · $total';
  }

