  bool _looksLikeTransportExpense(String text) {
    final normalized = _normalizeSearchText(text);
    return normalized.contains('starken') ||
        normalized.contains('kaudat') ||
        normalized.contains('courier') ||
        normalized.contains('flete') ||
        normalized.contains('encomienda') ||
