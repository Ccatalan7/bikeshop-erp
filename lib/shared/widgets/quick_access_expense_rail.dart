    _ocrSupplierRut = null;
    _setDescriptionText('');
    _referenceController.clear();
    _supplierController.clear();
    _expenseDate = DateTime.now();
    _documentType = ExpenseDocumentType.invoice;
    _selectedAccount = null;
    _selectedCategory = null;
    _selectedPaymentMethodId = null;
    _selectedSupplier = null;
    _appliedTemplate = null;
    _selectedPurchaseInvoice = null;
    _linkToPurchaseInvoice = false;
    _selectedLinkKind = 'general';
    _isPurchaseInvoicePickerOpen = false;
    _purchaseInvoiceSearchController.clear();
  }

  String _dropFileName(DropItem file) {
    final name = file.name.trim();
    if (name.isNotEmpty) return name;
    return file.path.split(RegExp(r'[/\\]')).last;
  }

  String _fileExtension(String fileName, {String? fallback}) {
    final fallbackText = fallback?.trim().toLowerCase();
    final dotIndex = fileName.lastIndexOf('.');
    if (dotIndex >= 0 && dotIndex < fileName.length - 1) {
      return fileName.substring(dotIndex + 1).toLowerCase();
    }
    return fallbackText ?? '';
  }

  String _inferQuickOcrExtension(Uint8List bytes) {
    if (bytes.length >= 4 &&
        bytes[0] == 0x25 &&
        bytes[1] == 0x50 &&
        bytes[2] == 0x44 &&
        bytes[3] == 0x46) {
      return 'pdf';
    }
    if (bytes.length >= 8 &&
        bytes[0] == 0x89 &&
        bytes[1] == 0x50 &&
        bytes[2] == 0x4E &&
        bytes[3] == 0x47) {
      return 'png';
    }
    if (bytes.length >= 3 &&
        bytes[0] == 0xFF &&
        bytes[1] == 0xD8 &&
        bytes[2] == 0xFF) {
      return 'jpg';
    }
    return '';
  }

  String? _supplierNameFromFileName(String fileName) {
    final name = fileName
        .replaceAll(RegExp(r'\.[A-Za-z0-9]+$'), '')
        .replaceAll(RegExp(r'[_-]+'), ' ')
        .trim();
    return name.isEmpty ? null : name;
  }

  String _defaultOcrDescription(ParsedInvoice parsedInvoice) {
    final supplierName = parsedInvoice.supplierName?.trim();
    final itemDescriptions = parsedInvoice.lineItems
        .map((item) => item.description.trim())
        .where((description) => description.isNotEmpty)
        .take(2)
        .toList(growable: false);
    if (itemDescriptions.isNotEmpty) {
      return [
        itemDescriptions.join(' + '),
        if (supplierName != null && supplierName.isNotEmpty) supplierName,
      ].join(' · ');
    }
    if (supplierName != null && supplierName.isNotEmpty) {
      return 'Gasto $supplierName';
    }
    return 'Gasto escaneado';
  }

  String _descriptionForOcrResult(
    _QuickExpenseOcrResult result,
    shared_supplier.Supplier? supplier,
  ) {
    if (!result.isTransportExpense) {
      return result.description ?? _defaultOcrDescription(result.parsedInvoice);
    }

    final supplierName = supplier?.displayName ??
        supplier?.name ??
        result.parsedInvoice.supplierName?.trim() ??
        'proveedor';
    final reference =
        (result.reference ?? result.parsedInvoice.invoiceNumber)?.trim();
    return [
      'Flete $supplierName',
      if (reference != null && reference.isNotEmpty) 'factura $reference',
    ].join(' · ');
  }

  bool _looksLikeTransportExpense(String text) {
    final normalized = _normalizeSearchText(text);
    return normalized.contains('starken') ||
        normalized.contains('kaudat') ||
        normalized.contains('courier') ||
        normalized.contains('flete') ||
        normalized.contains('encomienda') ||
        normalized.contains('transporte') ||
        normalized.contains('despacho') ||
        normalized.contains('envio');
  }

  bool _looksLikeTransportOnlyExpense(ParsedInvoice parsedInvoice) {
    final supplierText = _normalizeSearchText(parsedInvoice.supplierName ?? '');
    if (supplierText.contains('starken') ||
        supplierText.contains('kaudat') ||
        supplierText.contains('courier') ||
        supplierText.contains('transportes') ||
        supplierText.contains('encomiendas')) {
      return true;
    }

    if (parsedInvoice.lineItems.isNotEmpty) {
      final hasNonTransportItem = parsedInvoice.lineItems.any((item) {
        final text = _normalizeSearchText(item.description);
        return !(text.contains('envio') ||
            text.contains('despacho') ||
            text.contains('flete') ||
            text.contains('transporte'));
      });
      if (hasNonTransportItem) return false;
    }

    final documentText = parsedInvoice.rawText;
    final normalizedDocument = _normalizeSearchText(documentText);
    if ((normalizedDocument.contains('nombre del producto') ||
            normalizedDocument.contains('detalle')) &&
        (normalizedDocument.contains('costo de envio') ||
            normalizedDocument.contains('despacho por cuenta del emisor'))) {
      return false;
    }
    return _looksLikeTransportExpense(
      '${parsedInvoice.supplierName ?? ''}\n$documentText',
    );
  }

  bool _looksLikeOfficeSupplyExpense(ParsedInvoice parsedInvoice) {
    final text = _normalizeSearchText([
      ...parsedInvoice.lineItems.map((item) => item.description),
      parsedInvoice.rawText,
    ].join('\n'));
    return text.contains('rj45') ||
        text.contains('cable de red') ||
        text.contains('cable ethernet') ||
        text.contains('patch cord');
  }

  bool _looksLikeMercadoLibreInvoice(ParsedInvoice parsedInvoice) {
    final text = _normalizeSearchText(parsedInvoice.rawText);
    return (text.contains('mercadolibre') || text.contains('mercado libre')) &&
        text.contains('por cuenta y orden del vendedor');
  }

  _UtilityExpenseKind? _inferUtilityKind(String text) {
    final normalized = _normalizeSearchText(text);
    if (normalized.contains('esval') ||
        normalized.contains('agua') ||
        normalized.contains('aguas') ||
        normalized.contains('sanitari') ||
        normalized.contains('alcantarill')) {
      return _UtilityExpenseKind.water;
    }
    if (normalized.contains('luz') ||
        normalized.contains('electric') ||
        normalized.contains('energia') ||
        normalized.contains('enel') ||
        normalized.contains('cge') ||
        normalized.contains('chilquinta') ||
        normalized.contains('saesa') ||
        normalized.contains('frontel')) {
      return _UtilityExpenseKind.electricity;
    }
    return null;
  }

  Account? _resolveUtilityAccount(_QuickExpenseOcrResult result) {
    final kind = result.utilityKind;
    if (kind == null) return null;

    final preferredCodes = switch (kind) {
      _UtilityExpenseKind.water => const ['6202-01'],
      _UtilityExpenseKind.electricity => const ['6202-02'],
    };
    for (final code in preferredCodes) {
      for (final account in _accounts) {
        if (account.code == code) return account;
      }
    }

    final nameNeedles = switch (kind) {
      _UtilityExpenseKind.water => const ['agua'],
      _UtilityExpenseKind.electricity => const ['luz', 'electric'],
    };
    for (final account in _accounts) {
      final normalized = _normalizeSearchText(
        '${account.name} ${account.description ?? ''}',
      );
      if (nameNeedles.any(normalized.contains)) return account;
    }
    return null;
  }

  Account? _resolveDigitalInfrastructureAccount(
    _QuickExpenseOcrResult result,
  ) {
    if (!result.isDigitalInfrastructureExpense) return null;

    for (final code in const [
      QuickExpenseReceiptParser.domainExpenseAccountCode,
    ]) {
      for (final account in _accounts) {
        if (account.code == code) return account;
      }
    }

    for (final account in _accounts) {
      final normalized = _normalizeSearchText(
        '${account.name} ${account.description ?? ''}',
      );
      if (normalized.contains('dominio') ||
          normalized.contains('hosting') ||
          normalized.contains('alojamiento web')) {
        return account;
      }
    }
    return null;
  }

  Account? _resolveOfficeSupplyAccount(_QuickExpenseOcrResult result) {
    if (!result.isOfficeSupplyExpense) return null;

    for (final account in _accounts) {
      if (account.code == '6205') return account;
    }

    for (final account in _accounts) {
      final normalized = _normalizeSearchText(
        '${account.name} ${account.description ?? ''}',
      );
      if (normalized.contains('suministro') ||
          normalized.contains('insumo') ||
          normalized.contains('oficina')) {
        return account;
      }
    }
    return null;
  }

  Account? _resolveTransportAccount(_QuickExpenseOcrResult result) {
    if (!result.isTransportExpense) return null;

    for (final account in _accounts) {
      if (account.code == '6402') return account;
    }

    for (final account in _accounts) {
      final normalized = _normalizeSearchText(
        '${account.name} ${account.description ?? ''}',
      );
      if (normalized.contains('transporte') ||
          normalized.contains('flete') ||
          normalized.contains('encomienda') ||
          normalized.contains('envio') ||
          normalized.contains('courier')) {
        return account;
      }
    }
    return null;
  }

  ExpenseCategory? _resolveCategoryForAccount(Account? account) {
    if (account?.id == null) return null;

    final preferredName = _preferredCategoryNameForAccount(account!);
    if (preferredName != null) {
      final normalizedPreferred = _normalizeSearchText(preferredName);
      for (final category in _categories) {
        if (_normalizeSearchText(category.name) == normalizedPreferred) {
          return category;
        }
      }
    }

    for (final category in _categories) {
      if (category.defaultAccountId == account.id) return category;
    }

    final normalizedAccountName = _normalizeSearchText(account.name);
    for (final category in _categories) {
      final normalizedCategoryName = _normalizeSearchText(category.name);
      if (normalizedCategoryName == normalizedAccountName) return category;
    }
    return null;
  }

  String? _preferredCategoryNameForAccount(Account account) {
    final code = account.code.trim();
    final normalized = _normalizeSearchText(
      '${account.name} ${account.description ?? ''}',
    );

    if (code == '6202' ||
        code.startsWith('6202-') ||
        normalized.contains('agua') ||
        normalized.contains('esval') ||
        normalized.contains('luz') ||
        normalized.contains('electric') ||
        normalized.contains('energia')) {
      return 'Servicios Básicos';
    }

    if (code == '6203' ||
        normalized.contains('telefon') ||
        normalized.contains('internet')) {
      return 'Telefonía e Internet';
    }

    if (code == '6204' || normalized.contains('mantencion')) {
      return 'Mantención y Reparaciones';
    }

    if (code == '6205' ||
        normalized.contains('suministro') ||
        normalized.contains('insumo') ||
        normalized.contains('oficina')) {
      return 'Suministros de Oficina';
    }

    if (code == '6207' ||
        code == '6207-01' ||
        normalized.contains('dominio') ||
        normalized.contains('hosting') ||
        normalized.contains('servicio digital') ||
        normalized.contains('software') ||
        normalized.contains('infraestructura web')) {
      return QuickExpenseReceiptParser.domainExpenseCategoryName;
    }

    if (code == '6402' ||
        normalized.contains('transporte') ||
        normalized.contains('flete') ||
        normalized.contains('encomienda') ||
        normalized.contains('envio') ||
        normalized.contains('courier')) {
      return 'Gastos por Transporte';
    }

    return null;
  }

  PaymentMethod? _findPaymentMethodByNeedles(Iterable<String> needles) {
    for (final method in _paymentMethods) {
      final text = _normalizeSearchText('${method.code} ${method.name}');
      if (needles.any(text.contains)) return method;
    }
    return null;
  }

  PaymentMethod? _findCardPaymentMethod({String? preferredKind}) {
    if (preferredKind == null) {
      for (final method in _paymentMethods) {
        final code = _normalizeSearchText(method.code);
        final text = _normalizeSearchText('${method.code} ${method.name}');
        final isCombinedCard = code == 'card' ||
            ((text.contains('debito') || text.contains('debit')) &&
                (text.contains('credito') || text.contains('credit')));
        if (isCombinedCard) return method;
      }
    }

    final preferredNeedles = switch (preferredKind) {
      'debit' => const ['debit_card', 'debit', 'debito'],
      'credit' => const ['credit_card', 'credit', 'credito'],
      _ => const ['card', 'tarjeta'],
    };

    final preferred = _findPaymentMethodByNeedles(preferredNeedles);
    if (preferred != null) return preferred;

    return _findPaymentMethodByNeedles(const [
      'debit_card',
      'credit_card',
      'card',
      'tarjeta',
      'debit',
      'debito',
      'credit',
      'credito',
    ]);
  }

  PaymentMethod? _resolvePaymentMethodFromHint(String? rawHint) {
    final hint = _normalizeSearchText(rawHint ?? '');
    if (hint.isEmpty) return null;

    if (hint.contains('debit') || hint.contains('debito')) {
      return _findCardPaymentMethod(preferredKind: 'debit');
    }
    if (hint.contains('credit') || hint.contains('credito')) {
      return _findCardPaymentMethod(preferredKind: 'credit');
    }
    if (hint.contains('card') || hint.contains('tarjeta')) {
      return _findCardPaymentMethod();
    }
    if (hint.contains('transfer')) {
      return _findPaymentMethodByNeedles(const [
        'bank_transfer',
        'transfer',
        'banco',
      ]);
    }
    if (hint.contains('cash') || hint.contains('efectivo')) {
      return _findPaymentMethodByNeedles(const ['cash', 'efectivo']);
    }

    return null;
  }

  shared_supplier.Supplier? _matchSupplierFromOcr(
    ParsedInvoice parsedInvoice, {
    String? sourceSupplierId,
    String? sourceSupplierName,
  }) {
    final sourceId = sourceSupplierId?.trim();
    if (sourceId != null && sourceId.isNotEmpty) {
      for (final supplier in _suppliers) {
        if (supplier.id == sourceId) return supplier;
      }
    }

    final sourceName = _normalizeSearchText(sourceSupplierName ?? '');
    if (sourceName.isNotEmpty) {
      for (final supplier in _suppliers) {
        final identityTerms = supplier.identityNames
            .map(_normalizeSearchText)
            .where((term) => term.length >= 3);
        for (final term in identityTerms) {
          if (term == sourceName ||
              term.contains(sourceName) ||
              sourceName.contains(term)) {
            return supplier;
          }
        }
      }
    }

    final parsedRut = _normalizeRut(parsedInvoice.rut);
    if (parsedRut.isNotEmpty) {
      for (final supplier in _suppliers) {
        if (_normalizeRut(supplier.rut) == parsedRut) return supplier;
      }
    }

    final parsedName = _normalizeSearchText(parsedInvoice.supplierName ?? '');
    final documentText = _normalizeSearchText(parsedInvoice.rawText);

    if (_looksLikeKaudatStarken(parsedInvoice) ||
        parsedName.contains('kaudat')) {
      for (final supplier in _suppliers) {
        final supplierText = _supplierSearchText(supplier);
        if (supplierText.contains('starken') ||
            supplierText.contains('kaudat')) {
          return supplier;
        }
      }
    }

    if (parsedName.isEmpty && documentText.isEmpty) return null;

    for (final supplier in _suppliers) {
      final identityTerms = supplier.identityNames
          .map(_normalizeSearchText)
          .where((term) => term.length >= 3);
      for (final term in identityTerms) {
        if (parsedName.isNotEmpty &&
            (term == parsedName ||
                term.contains(parsedName) ||
                parsedName.contains(term))) {
          return supplier;
        }
        if (term.length >= 5 && documentText.startsWith(term)) {
          return supplier;
        }
      }
    }
    return null;
  }

  bool _looksLikeKaudatStarken(ParsedInvoice parsedInvoice) {
    final text = _normalizeSearchText(
      '${parsedInvoice.supplierName ?? ''}\n${parsedInvoice.rawText}',
    );
    return text.contains('kaudat') &&
        (text.contains('flete') ||
            text.contains('courier') ||
            text.contains('starken'));
  }

  String _supplierSearchText(shared_supplier.Supplier supplier) {
    return _normalizeSearchText([
      ...supplier.identityNames,
      supplier.rut ?? '',
      supplier.phone ?? '',
    ].join(' '));
  }

  String _supplierSubtitle(shared_supplier.Supplier supplier) {
    final parts = <String>[
      if ((supplier.legalName ?? '').trim().isNotEmpty)
        supplier.legalName!.trim(),
      if ((supplier.tradeName ?? '').trim().isNotEmpty)
        supplier.tradeName!.trim(),
      if (supplier.aliases.isNotEmpty) supplier.aliases.take(3).join(', '),
    ];
    if (parts.isEmpty) return supplier.rut ?? '';
    return parts.join(' · ');
  }

  String _normalizeRut(String? value) {
    return (value ?? '')
        .replaceAll(RegExp(r'[^0-9kK]'), '')
        .toLowerCase()
        .trim();
  }

  double _parseAmount(String text) {
    if (text.trim().isEmpty) return 0;
    final normalized = text.replaceAll('.', '').replaceAll(',', '.');
    return double.tryParse(normalized) ?? 0;
  }

  String _formatDate(DateTime date) {
    return DateFormat('dd/MM', 'es_CL').format(date);
  }

  String _paymentStatusLabel(ExpensePaymentStatus status) {
    switch (status) {
