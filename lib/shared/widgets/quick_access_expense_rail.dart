  String _purchaseInvoiceSearchText(PurchaseInvoice invoice) {
    return _normalizeSearchText(
      [
        _formatPurchaseInvoiceLabel(invoice),
        invoice.invoiceNumber,
        invoice.supplierName ?? '',
        invoice.supplierRut ?? '',
        invoice.status.displayName,
        invoice.total.round().toString(),
        _numberFormat.format(invoice.total.round()),
      ].join(' '),
    ).replaceAll(RegExp(r'[^a-z0-9]+'), ' ');
  }

