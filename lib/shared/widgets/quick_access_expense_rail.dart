  @override
  void initState() {
    super.initState();
    _amountController.addListener(_handleFormValueChanged);
    _descriptionController.addListener(_handleDescriptionChanged);
    WidgetsBinding.instance.addPostFrameCallback((_) {
      _loadData();
    });
  }

  @override
  void dispose() {
    _amountController.removeListener(_handleFormValueChanged);
    _descriptionController.removeListener(_handleDescriptionChanged);
    _amountController.dispose();
    _descriptionController.dispose();
    _referenceController.dispose();
    _supplierController.dispose();
    _purchaseInvoiceSearchController.dispose();
    _purchaseInvoiceSearchFocusNode.dispose();
    super.dispose();
  }

  bool get _hasIva => _documentType == ExpenseDocumentType.invoice;

  double get _totalAmount => _parseAmount(_amountController.text);

  double get _netAmount {
    if (!_hasIva || _totalAmount <= 0) return _totalAmount;
    return _totalAmount / 1.19;
  }

  double get _ivaAmount {
    if (!_hasIva || _totalAmount <= 0) return 0;
    return _totalAmount - _netAmount;
  }

  Iterable<shared_supplier.Supplier> get _supplierSuggestions {
    final query = _normalizeSearchText(_supplierController.text);
    final rutQuery = _normalizeRut(_supplierController.text);
    if (query.isEmpty) {
      return const Iterable<shared_supplier.Supplier>.empty();
    }

    return _suppliers.where((supplier) {
      return _supplierSearchText(supplier).contains(query) ||
          (rutQuery.isNotEmpty &&
              _normalizeRut(supplier.rut).contains(rutQuery));
    }).take(6);
  }

  double get _monthExpenseTotal {
    final now = DateTime.now();
    return _recentExpenses
        .where((expense) =>
            expense.issueDate.year == now.year &&
            expense.issueDate.month == now.month)
        .fold<double>(0, (sum, expense) => sum + expense.totalAmount);
  }

  double get _todayExpenseTotal {
    final now = DateTime.now();
    return _recentExpenses.where((expense) {
      final issueDate = expense.issueDate;
      return issueDate.year == now.year &&
          issueDate.month == now.month &&
          issueDate.day == now.day;
    }).fold<double>(0, (sum, expense) => sum + expense.totalAmount);
  }

  double get _pendingBalanceTotal {
    return _recentExpenses
        .where((expense) => expense.paymentStatus != ExpensePaymentStatus.paid)
        .fold<double>(0, (sum, expense) => sum + expense.balance);
  }

  PaymentMethod? get _selectedPaymentMethod {
    final selectedId = _selectedPaymentMethodId;
    if (selectedId == null) return null;

    for (final method in _paymentMethods) {
      if (method.id == selectedId) return method;
    }

    return null;
  }

  List<PurchaseInvoice> get _filteredPurchaseInvoices {
    final query = _normalizeSearchText(_purchaseInvoiceSearchController.text)
        .replaceAll(RegExp(r'[^a-z0-9]+'), ' ')
        .trim();
    if (query.isEmpty) {
      return _purchaseInvoices.take(12).toList(growable: false);
    }

    final tokens = query
        .split(RegExp(r'\s+'))
        .where((token) => token.isNotEmpty)
        .toList(growable: false);
    return _purchaseInvoices
        .where((invoice) {
          final searchText = _purchaseInvoiceSearchText(invoice);
          return tokens.every(searchText.contains);
        })
        .take(12)
        .toList(growable: false);
  }

  void _handleFormValueChanged() {
    if (!mounted) return;
    setState(() {});
  }

  void _handleDescriptionChanged() {
    if (_isUpdatingDescription) {
      return;
    }

    if (_descriptionWasAutoGenerated &&
        _descriptionController.text != _lastAutoDescription) {
      _descriptionWasAutoGenerated = false;
      _lastAutoDescription = null;
    }

    if (!mounted || _appliedTemplate != null) {
      _handleFormValueChanged();
      return;
    }

    final match = _findTemplateForText(_descriptionController.text);
    if (match != null) {
      _applyTemplate(
        match,
        overwriteAmount: false,
        overwriteDescription: false,
        showMessage: false,
      );
      return;
    }

    _handleFormValueChanged();
  }

  void _setDescriptionText(String value, {bool autoGenerated = false}) {
    _isUpdatingDescription = true;
    _descriptionController.text = value;
    _descriptionController.selection = TextSelection.collapsed(
      offset: _descriptionController.text.length,
    );
    _isUpdatingDescription = false;
    _descriptionWasAutoGenerated = autoGenerated;
    _lastAutoDescription = autoGenerated ? value : null;
  }

  int get _pendingExpenseCount {
    return _recentExpenses
        .where((expense) => expense.paymentStatus != ExpensePaymentStatus.paid)
        .length;
  }

  Future<void> _loadData({bool refresh = false}) async {
    if (!mounted) return;

    setState(() {
      _isLoading = true;
      _loadError = null;
    });

    try {
      final accountingService = context.read<AccountingService>();
      final expenseService = context.read<ExpenseService>();
      final purchaseService = context.read<PurchaseService>();
      final paymentMethodService = context.read<PaymentMethodService>();

      final results = await Future.wait([
        accountingService.getAccounts(),
        expenseService.fetchCategories(forceRefresh: refresh),
        expenseService.fetchExpenses(forceRefresh: refresh),
        purchaseService.getSuppliers(),
        paymentMethodService.loadPaymentMethods(forceRefresh: refresh),
        NumberGenerationService().previewExpenseNumber(),
        expenseService.fetchTemplates(forceRefresh: refresh),
        purchaseService.getPurchaseInvoicesForList(forceRefresh: refresh),
      ]);

      final allAccounts = (results[0] as List<Account>)
          .where((account) =>
              account.type == AccountType.expense && account.isActive)
          .toList()
        ..sort((left, right) => left.code.compareTo(right.code));
      final categories = (results[1] as List<ExpenseCategory>)
        ..sort((left, right) => left.name.compareTo(right.name));
      final expenses = (results[2] as List<Expense>)
        ..sort((left, right) => right.issueDate.compareTo(left.issueDate));
      final suppliers = (results[3] as List<shared_supplier.Supplier>)
          .where((supplier) => supplier.isActive)
          .toList()
        ..sort((left, right) => left.name.compareTo(right.name));
      final methods =
          List<PaymentMethod>.from(paymentMethodService.paymentMethods)
            ..sort((left, right) => left.sortOrder.compareTo(right.sortOrder));
      final nextNumber = results[5] as String;
      final templates = (results[6] as List<ExpenseTemplate>)
          .where((template) => template.isActive)
          .toList()
        ..sort((left, right) {
          final priority = left.priority.compareTo(right.priority);
          if (priority != 0) return priority;
          return left.name.compareTo(right.name);
        });
      final purchaseInvoices = (results[7] as List<PurchaseInvoice>)
          .where((invoice) => invoice.id != null && invoice.id!.isNotEmpty)
          .take(40)
          .toList(growable: false);

      if (!mounted) return;

      setState(() {
        _accounts = allAccounts;
        _categories = categories;
        _recentExpenses = expenses.take(6).toList(growable: false);
        _suppliers = suppliers;
        _paymentMethods = methods;
        _templates = templates;
        _purchaseInvoices = purchaseInvoices;

        _selectedAccount ??= _resolveDefaultAccount(allAccounts);
        _selectedCategory ??=
            _resolveDefaultCategory(categories, _selectedAccount);
        _selectedPaymentMethodId = _resolveSelectedPaymentMethodId(methods);

        _bannerMessage = 'Próximo folio: $nextNumber';
        _isLoading = false;
      });
    } catch (error) {
      if (!mounted) return;
      setState(() {
        _isLoading = false;
        _loadError = error.toString();
      });
    }
  }

  Account? _resolveDefaultAccount(List<Account> accounts) {
    if (accounts.isEmpty) return null;
    for (final preferredCode in ['5200', '6100', '6101']) {
      final match = accounts.where((account) => account.code == preferredCode);
      if (match.isNotEmpty) return match.first;
    }
    return accounts.first;
  }

  ExpenseCategory? _resolveDefaultCategory(
    List<ExpenseCategory> categories,
    Account? selectedAccount,
  ) {
    if (categories.isEmpty) return null;
    if (selectedAccount != null) {
      final matchingCategories = categories.where(
        (category) => category.defaultAccountId == selectedAccount.id,
      );
      if (matchingCategories.isNotEmpty) {
        return matchingCategories.first;
      }
    }
    return null;
  }

  PaymentMethod? _resolveDefaultPaymentMethod(List<PaymentMethod> methods) {
    if (methods.isEmpty) return null;
    for (final preferredCode in ['cash', 'transfer', 'card']) {
      final match = methods.where((method) => method.code == preferredCode);
      if (match.isNotEmpty) return match.first;
    }
    return methods.first;
  }

  String? _resolveSelectedPaymentMethodId(List<PaymentMethod> methods) {
    if (methods.isEmpty) return null;

    final currentId = _selectedPaymentMethodId;
    if (currentId != null) {
      for (final method in methods) {
        if (method.id == currentId) return currentId;
      }
    }

    return _resolveDefaultPaymentMethod(methods)?.id;
  }

  ExpenseTemplate? _findTemplateForCategory(ExpenseCategory category) {
    for (final template in _templates) {
      if (template.triggerCategoryId == category.id ||
          template.defaultCategoryId == category.id) {
        return template;
      }
    }
    return null;
  }

  ExpenseTemplate? _findTemplateForSupplier(shared_supplier.Supplier supplier) {
    for (final template in _templates) {
      if (template.triggerSupplierId == supplier.id ||
          template.defaultSupplierId == supplier.id) {
        return template;
      }
    }
    return null;
  }

  ExpenseTemplate? _findTemplateForText(String rawText) {
    final text = _normalizeSearchText(rawText);
    if (text.length < 3) return null;

    for (final template in _templates) {
      for (final keyword in template.triggerKeywords) {
        final normalizedKeyword = _normalizeSearchText(keyword);
        if (normalizedKeyword.length >= 3 && text.contains(normalizedKeyword)) {
          return template;
        }
      }
    }
    return null;
  }

  String _normalizeSearchText(String value) {
    return value
        .toLowerCase()
        .replaceAll(RegExp(r'[áàäâ]'), 'a')
        .replaceAll(RegExp(r'[éèëê]'), 'e')
        .replaceAll(RegExp(r'[íìïî]'), 'i')
        .replaceAll(RegExp(r'[óòöô]'), 'o')
        .replaceAll(RegExp(r'[úùüû]'), 'u')
        .replaceAll('ñ', 'n')
        .trim();
  }

  void _applyTemplate(
    ExpenseTemplate template, {
    bool overwriteAmount = true,
    bool overwriteDescription = true,
    bool showMessage = true,
  }) {
    final categoryId = template.defaultCategoryId ?? template.triggerCategoryId;
    final accountId = template.defaultAccountId;
    final supplierId = template.defaultSupplierId ?? template.triggerSupplierId;

    ExpenseCategory? category;
    if (categoryId != null) {
      for (final item in _categories) {
        if (item.id == categoryId) {
          category = item;
          break;
        }
      }
    }

    Account? account;
    if (accountId != null) {
      for (final item in _accounts) {
        if (item.id == accountId) {
          account = item;
          break;
        }
      }
    }

    shared_supplier.Supplier? supplier;
    if (supplierId != null) {
      for (final item in _suppliers) {
        if (item.id == supplierId) {
          supplier = item;
          break;
        }
      }
    }

    PaymentMethod? method;
    final methodId = template.defaultPaymentMethodId;
    if (methodId != null) {
      for (final item in _paymentMethods) {
        if (item.id == methodId) {
          method = item;
          break;
        }
      }
    }

    Account? categoryAccount;
    final categoryAccountId = category?.defaultAccountId;
    if (categoryAccountId != null) {
      for (final item in _accounts) {
        if (item.id == categoryAccountId) {
          categoryAccount = item;
          break;
        }
      }
    }

    setState(() {
      _appliedTemplate = template;
      _selectedCategory = category ?? _selectedCategory;
      _selectedAccount = account ?? categoryAccount ?? _selectedAccount;
      _selectedSupplier = supplier ?? _selectedSupplier;
      if (supplier != null) {
        _supplierController.text = supplier.name;
      } else if ((template.defaultSupplierName ?? '').isNotEmpty) {
        _supplierController.text = template.defaultSupplierName!;
      }
      if (method != null) {
        _selectedPaymentMethodId = method.id;
      }
      _documentType = template.defaultDocumentType;
      if (overwriteAmount) {
        final amount = template.defaultAmount ?? 0;
        _amountController.text = _numberFormat.format(amount.round());
      }
      if (overwriteDescription) {
        _setDescriptionText((template.defaultDescription ?? '').trim());
      } else if (_descriptionController.text.trim().isEmpty &&
          (template.defaultDescription ?? '').trim().isNotEmpty) {
        _setDescriptionText(template.defaultDescription!.trim());
      }
      _linkToPurchaseInvoice = template.linkPurchaseInvoice;
      _selectedLinkKind = template.linkKind;
      if (!template.linkPurchaseInvoice) {
        _selectedPurchaseInvoice = null;
      }
      if (overwriteDescription &&
          template.linkPurchaseInvoice &&
          (template.defaultDescription ?? '').trim().isEmpty) {
        _applyLinkedInvoiceDescription(force: true);
      }
    });

    if (showMessage) {
      _showMessage('Plantilla aplicada: ${template.name}', isError: false);
    }
  }

  void _applyLinkedInvoiceDescription({bool force = false}) {
    final invoice = _selectedPurchaseInvoice;
    if (!_linkToPurchaseInvoice || invoice == null) return;

    final generated = _buildLinkedPurchaseDescription(invoice);
    final canReplace = force ||
        _descriptionWasAutoGenerated ||
        _descriptionController.text.trim().isEmpty;

    if (!canReplace) return;
    _setDescriptionText(generated, autoGenerated: true);
  }

  String _buildLinkedPurchaseDescription(PurchaseInvoice invoice) {
    final invoiceNumber = invoice.invoiceNumber.trim().isEmpty
        ? 'factura de compra'
        : 'compra ${invoice.invoiceNumber.trim()}';
    final supplier = (invoice.supplierName ?? '').trim();
    final suffix = supplier.isEmpty ? '' : ' · $supplier';

    switch (_selectedLinkKind) {
      case 'delivery':
        return 'Entrega / transporte $invoiceNumber$suffix';
      case 'import_cost':
        return 'Costo de importación $invoiceNumber$suffix';
      default:
        return 'Gasto relacionado $invoiceNumber$suffix';
    }
  }

  void _clearAppliedTemplate() {
    setState(() {
      _appliedTemplate = null;
    });
  }

  Future<void> _deleteAppliedTemplate() async {
    final template = _appliedTemplate;
    if (template?.id == null) return;
    final expenseService = context.read<ExpenseService>();

    final shouldDelete = await showDialog<bool>(
      context: context,
      builder: (dialogContext) => AlertDialog(
        title: const Text('Eliminar plantilla'),
        content: Text('¿Eliminar "${template!.name}"?'),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(dialogContext).pop(false),
            child: const Text('Cancelar'),
          ),
          FilledButton(
            onPressed: () => Navigator.of(dialogContext).pop(true),
            child: const Text('Eliminar'),
          ),
        ],
      ),
    );

    if (shouldDelete != true || !mounted) return;

    try {
      await expenseService.deleteTemplate(template!.id!);
      if (!mounted) return;
      setState(() {
        _templates = _templates
            .where((item) => item.id != template.id)
            .toList(growable: false);
        _appliedTemplate = null;
      });
      _showMessage('Plantilla eliminada.', isError: false);
    } catch (error) {
      _showMessage('No se pudo eliminar la plantilla: $error', isError: true);
    }
  }

  Future<void> _pickExpenseDate() async {
    final pickedDate = await showDatePicker(
      context: context,
      initialDate: _expenseDate,
      firstDate: DateTime(2020),
      lastDate: DateTime.now().add(const Duration(days: 365)),
      locale: const Locale('es', 'CL'),
    );

    if (pickedDate == null || !mounted) return;
    setState(() => _expenseDate = pickedDate);
  }

  void _applyAmountPreset(int amount) {
    setState(() {
      _amountController.text = _numberFormat.format(amount);
    });
  }

  void _selectCategory(ExpenseCategory category) {
    setState(() {
      _selectedCategory = category;
      if (category.defaultAccountId != null) {
        for (final account in _accounts) {
          if (account.id == category.defaultAccountId) {
            _selectedAccount = account;
            break;
          }
        }
      }
    });

    final template = _findTemplateForCategory(category);
    if (template != null) {
      _applyTemplate(template);
    }
  }

  void _selectSupplier(shared_supplier.Supplier supplier) {
    setState(() {
      _selectedSupplier = supplier;
      _supplierController.text = supplier.name;
    });

    final template = _findTemplateForSupplier(supplier);
    if (template != null) {
      _applyTemplate(template);
    }
  }

  void _clearSupplier() {
    setState(() {
      _selectedSupplier = null;
      _supplierController.clear();
      if (_appliedTemplate?.triggerSupplierId != null ||
          _appliedTemplate?.defaultSupplierId != null) {
        _appliedTemplate = null;
      }
    });
  }

  Future<void> _saveQuickExpense() async {
    FocusScope.of(context).unfocus();

    if (_selectedAccount?.id == null) {
      _showMessage('Selecciona una cuenta de gasto.', isError: true);
      return;
    }

    if (_selectedPaymentMethod == null) {
      _showMessage('Selecciona un método de pago.', isError: true);
      return;
    }

    if (_totalAmount <= 0) {
      _showMessage('Ingresa un monto válido.', isError: true);
      return;
    }

    if (_linkToPurchaseInvoice && _selectedPurchaseInvoice == null) {
      _showMessage(
        'Selecciona la factura de compra relacionada.',
        isError: true,
      );
      return;
    }

    final description = _descriptionController.text.trim();
    final supplierName =
        _selectedSupplier?.name ?? _supplierController.text.trim();
    final expenseService = context.read<ExpenseService>();

    final tenantId = await TenantService().getTenantId();
    if (tenantId == null) {
      _showMessage('No se pudo obtener el tenant actual.', isError: true);
      return;
    }

    setState(() => _isSaving = true);

    try {
      final expenseNumber = await NumberGenerationService().nextExpenseNumber();
      final now = DateTime.now();
      final expense = Expense(
        tenantId: tenantId,
        expenseNumber: expenseNumber,
        categoryId: _selectedCategory?.id,
        supplierId: _selectedSupplier?.id,
        supplierName: supplierName.isEmpty ? null : supplierName,
        supplierRut: _selectedSupplier?.rut,
        documentType: _documentType,
        documentNumber: _referenceController.text.trim().isEmpty
            ? null
            : _referenceController.text.trim(),
        issueDate: _expenseDate,
        currency: 'CLP',
        exchangeRate: 1,
        postingStatus: ExpensePostingStatus.posted,
        paymentStatus: ExpensePaymentStatus.paid,
        subtotal: _netAmount,
        taxAmount: _ivaAmount,
        totalAmount: _totalAmount,
        amountPaid: _totalAmount,
        balance: 0,
        notes: description.isEmpty ? null : description,
        reference: _referenceController.text.trim().isEmpty
            ? null
            : _referenceController.text.trim(),
        approvalStatus: ExpenseApprovalStatus.approved,
        postedAt: now,
        paidAt: now,
        paymentAccountId: _selectedPaymentMethod!.accountId,
        paymentMethodId: _selectedPaymentMethod!.id,
        updatedAt: now,
        lines: [
          ExpenseLine(
            tenantId: tenantId,
            lineIndex: 0,
            accountId: _selectedAccount!.id!,
            accountCode: _selectedAccount!.code,
            accountName: _selectedAccount!.name,
            description: description.isEmpty ? null : description,
            quantity: 1,
            unitPrice: _netAmount,
            subtotal: _netAmount,
            taxRate: _hasIva ? 19.0 : 0.0,
            taxAmount: _ivaAmount,
            total: _totalAmount,
          ),
        ],
      );

      final savedExpense = await expenseService.saveExpense(expense);
      final selectedPurchaseInvoice = _selectedPurchaseInvoice;
      if (selectedPurchaseInvoice?.id != null &&
          selectedPurchaseInvoice!.id!.isNotEmpty &&
          savedExpense.id != null) {
        await expenseService.saveExpenseLink(
          ExpenseLink(
            tenantId: tenantId,
            expenseId: savedExpense.id!,
            purchaseInvoiceId: selectedPurchaseInvoice.id!,
            linkKind: _selectedLinkKind,
            allocatedAmount: _totalAmount,
            notes: description.isEmpty ? null : description,
          ),
        );
      }
      if (!mounted) return;

      setState(() {
        _amountController.clear();
        _setDescriptionText('');
        _referenceController.clear();
        _expenseDate = DateTime.now();
        _documentType = ExpenseDocumentType.invoice;
        _appliedTemplate = null;
