  String _templateAppliedLabel(ExpenseTemplate template) {
    final parts = <String>['Aplicada: ${template.name}'];
    if (template.hasDefaultAmount) {
      parts.add(_currencyFormat.format(template.defaultAmount));
    }
    if (template.recurrenceIntervalMonths != null &&
        template.nextDueDate != null) {
      parts.add(
        '${_periodText(template.recurrenceIntervalMonths!)} desde ${_formatDate(template.nextDueDate!)}',
      );
    }
    if (template.reviewIsOverdue) {
      parts.add('revisión vencida');
    } else if (template.reviewIsSoon) {
      parts.add('revisar pronto');
    } else if (template.nextReviewDate != null) {
      final reviewMonths = _reviewIntervalMonths(template);
      parts.add(
        reviewMonths == null
            ? 'revisión ${_formatDate(template.nextReviewDate!)}'
            : 'revisión ${_periodText(reviewMonths)}',
      );
    }
    if (template.linkPurchaseInvoice) {
      parts.add('pedirá factura compra');
    }
    return parts.join(' · ');
  }

  String _periodText(int months) {
    switch (months) {
      case 1:
        return 'mensual';
      case 2:
        return 'cada 2 meses';
      case 3:
        return 'trimestral';
      case 6:
        return 'semestral';
      case 12:
        return 'anual';
      default:
        return 'cada $months meses';
    }
  }

