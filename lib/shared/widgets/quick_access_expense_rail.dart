  bool _isPresetPeriod(int? months) {
    return months == null || const {1, 2, 3, 6, 12}.contains(months);
  }

  String _periodPreset(int months) {
    return _isPresetPeriod(months) ? months.toString() : 'custom';
  }

  int? _periodMonthsFromSelection(String selection, String customValue) {
    if (selection != 'custom') {
      return int.tryParse(selection);
    }
    final value = int.tryParse(customValue.trim());
    if (value == null || value <= 0) return null;
    return value;
  }

  int? _reviewIntervalMonths(ExpenseTemplate? template) {
    final raw = template?.metadata['amount_review_interval_months'];
    if (raw is int) return raw;
    if (raw is num) return raw.toInt();
    return int.tryParse(raw?.toString() ?? '');
  }

