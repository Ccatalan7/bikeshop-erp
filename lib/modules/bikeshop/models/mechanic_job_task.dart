import 'package:flutter/foundation.dart';

/// Task type enumeration for mechanic job tasks
enum TaskType {
  diagnostic('diagnostic', 'Diagnóstico'),
  installPart('install_part', 'Instalar Repuesto'),
  performService('perform_service', 'Realizar Servicio'),
  qualityCheck('quality_check', 'Control de Calidad'),
  testRide('test_ride', 'Prueba de Rodaje'),
  cleanup('cleanup', 'Limpieza/Pulido'),
  general('general', 'Tarea General');

  final String value;
  final String displayName;

  const TaskType(this.value, this.displayName);

  static TaskType fromString(String value) {
    return TaskType.values.firstWhere(
      (e) => e.value == value,
      orElse: () => TaskType.general,
    );
  }
}

/// Task status enumeration
enum TaskStatus {
  pending('pending', 'Pendiente'),
  inProgress('in_progress', 'En Progreso'),
  completed('completed', 'Completado'),
  skipped('skipped', 'Omitido'),
  blocked('blocked', 'Bloqueado');

  final String value;
  final String displayName;

  const TaskStatus(this.value, this.displayName);

  static TaskStatus fromString(String value) {
    return TaskStatus.values.firstWhere(
      (e) => e.value == value,
      orElse: () => TaskStatus.pending,
    );
  }
}

/// Task priority enumeration
