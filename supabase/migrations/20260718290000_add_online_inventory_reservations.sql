-- Existing active orders are backfilled oldest-first. A conflicting historical
-- commitment fails the migration instead of silently accepting over-allocation.
do $$
declare
  v_order record;
begin
  for v_order in
    select orders.id
      from public.online_orders orders
     where orders.status not in ('cancelled', 'delivered')
       and exists (
         select 1
           from public.online_order_items item
           join public.products product
             on product.id = item.product_id
            and product.tenant_id = item.tenant_id
          where item.tenant_id = orders.tenant_id
            and item.order_id = orders.id
            and not coalesce(item.is_service, product.is_service, false)
            and coalesce(item.product_type, product.product_type) <> 'service'
            and coalesce(
                  item.purchase_treatment,
                  product.purchase_treatment,
                  'inventory'
                ) <> 'workshop_consumable'
            and coalesce(product.track_stock, true)
       )
       and not exists (
         select 1
           from public.stock_movements movement
          where orders.sales_invoice_id is not null
            and movement.tenant_id = orders.tenant_id
            and movement.reference =
                  'sales_invoice:' || orders.sales_invoice_id::text
            and movement.quantity < 0
       )
     order by orders.tenant_id, orders.created_at, orders.id
  loop
    perform public.ensure_online_order_inventory_reservations(
      v_order.id,
      'migration_backfill'
    );
  end loop;
end $$;

