create or replace function public.append_online_inventory_reservation_event(
  p_reservation public.online_order_inventory_reservations,
  p_event_type text,
  p_from_state text,
  p_to_state text,
  p_executor text,
  p_operation_key text,
  p_payload jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  if p_reservation.id is null
     or nullif(btrim(coalesce(p_operation_key, '')), '') is null
     or nullif(btrim(coalesce(p_executor, '')), '') is null then
    raise exception 'Reservation event identity is required'
      using errcode = '22023';
  end if;

  insert into public.online_order_inventory_reservation_events (
    tenant_id, reservation_id, order_id, order_item_id, product_id,
    event_type, from_state, to_state, quantity, cycle, actor_id,
    executor, operation_key, payload
  ) values (
    p_reservation.tenant_id,
    p_reservation.id,
    p_reservation.order_id,
    p_reservation.order_item_id,
    p_reservation.product_id,
    p_event_type,
    p_from_state,
    p_to_state,
    p_reservation.quantity,
    p_reservation.cycle,
    auth.uid(),
    btrim(p_executor),
    btrim(p_operation_key),
    coalesce(p_payload, '{}'::jsonb)
  )
  on conflict (tenant_id, operation_key) do nothing
  returning id into v_id;

  if v_id is null then
    select event.id into v_id
      from public.online_order_inventory_reservation_events event
     where event.tenant_id = p_reservation.tenant_id
       and event.operation_key = btrim(p_operation_key)
       and event.reservation_id = p_reservation.id
       and event.event_type = p_event_type;
    if not found then
      raise exception 'Reservation event operation key conflicts with another event'
        using errcode = '23505';
    end if;
  end if;

  return v_id;
end;
$$;

revoke all on function public.append_online_inventory_reservation_event(
  public.online_order_inventory_reservations,
  text, text, text, text, text, jsonb
) from public, anon, authenticated, service_role;

create or replace function public.online_order_inventory_reservation_ttl(
  p_tenant_id uuid,
  p_payment_method text
)
returns interval
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_method text := lower(btrim(coalesce(p_payment_method, 'transfer')));
  v_key text;
  v_default_minutes integer;
  v_max_minutes integer;
  v_raw text;
  v_minutes integer;
begin
  if p_tenant_id is null then
    raise exception 'Reservation tenant is required' using errcode = '22023';
  end if;

  if v_method in ('mercadopago', 'mercado_pago') then
    v_key := 'online_order_reservation_minutes_mercadopago';
    v_default_minutes := 30;
    v_max_minutes := 60;
  else
    v_key := 'online_order_reservation_minutes_transfer';
    v_default_minutes := 1440;
    v_max_minutes := 10080;
  end if;

  select setting.value into v_raw
    from public.website_settings setting
   where setting.tenant_id = p_tenant_id
     and setting.key = v_key
   limit 1;

  v_minutes := case
    when btrim(coalesce(v_raw, '')) ~ '^[0-9]{1,5}$'
      then btrim(v_raw)::integer
    else v_default_minutes
  end;
  v_minutes := greatest(5, least(v_minutes, v_max_minutes));
  return make_interval(mins => v_minutes);
end;
$$;

revoke all on function public.online_order_inventory_reservation_ttl(uuid, text)
  from public, anon, authenticated, service_role;

create or replace function public.expire_online_order_inventory_reservations(
  p_tenant_id uuid default null,
  p_limit integer default 500
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reservation public.online_order_inventory_reservations%rowtype;
  v_expired integer := 0;
begin
  for v_reservation in
    select reservation.*
      from public.online_order_inventory_reservations reservation
     where reservation.state = 'active'
       and reservation.expires_at <= clock_timestamp()
       and (p_tenant_id is null or reservation.tenant_id = p_tenant_id)
     order by reservation.expires_at, reservation.id
     for update skip locked
     limit greatest(1, least(coalesce(p_limit, 500), 5000))
  loop
    update public.online_order_inventory_reservations reservation
       set state = 'expired',
           expired_at = clock_timestamp(),
           updated_at = clock_timestamp(),
           version = reservation.version + 1
     where reservation.id = v_reservation.id
       and reservation.tenant_id = v_reservation.tenant_id
       and reservation.state = 'active'
     returning reservation.* into v_reservation;

    if found then
      perform public.append_online_inventory_reservation_event(
        v_reservation,
        'expired',
        'active',
        'expired',
        case when p_tenant_id is null then 'system_cron' else 'database_rpc' end,
        'reservation-expire:' || v_reservation.id::text || ':'
          || v_reservation.cycle::text,
        jsonb_build_object('expires_at', v_reservation.expires_at)
      );
      v_expired := v_expired + 1;
    end if;
  end loop;

  return v_expired;
end;
$$;

revoke all on function public.expire_online_order_inventory_reservations(uuid, integer)
  from public, anon, authenticated, service_role;

create or replace function public.online_product_available_quantity(
  p_tenant_id uuid,
  p_product_id uuid
)
returns integer
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_product public.products%rowtype;
  v_available integer;
begin
  select product.* into v_product
    from public.products product
   where product.id = p_product_id
     and product.tenant_id = p_tenant_id;
  if not found then
    return 0;
  end if;

  if coalesce(v_product.is_service, false)
     or v_product.product_type = 'service'
     or not coalesce(v_product.track_stock, true) then
    return greatest(
      coalesce(v_product.stock_quantity, v_product.inventory_qty, 0),
      0
    );
  end if;

  if coalesce(v_product.is_set, false) then
    select min(greatest(floor(
      (
        coalesce(component.stock_quantity, component.inventory_qty, 0)
        - coalesce(reserved.quantity, 0)
      )::numeric / set_component.quantity_in_set
    ), 0))::integer
      into v_available
      from public.product_set_components set_component
      join public.products component
        on component.id = set_component.component_product_id
       and component.tenant_id = set_component.tenant_id
      left join lateral (
        select coalesce(sum(reservation.quantity), 0)::integer as quantity
          from public.online_order_inventory_reservations reservation
         where reservation.tenant_id = component.tenant_id
           and reservation.product_id = component.id
           and reservation.state = 'active'
           and reservation.expires_at > clock_timestamp()
      ) reserved on true
     where set_component.tenant_id = p_tenant_id
       and set_component.set_product_id = p_product_id;
    return greatest(coalesce(v_available, 0), 0);
  end if;

  select greatest(
    coalesce(v_product.stock_quantity, v_product.inventory_qty, 0)
      - coalesce(sum(reservation.quantity), 0),
    0
  )::integer
    into v_available
    from public.online_order_inventory_reservations reservation
   where reservation.tenant_id = p_tenant_id
     and reservation.product_id = p_product_id
     and reservation.state = 'active'
     and reservation.expires_at > clock_timestamp();

  return greatest(coalesce(v_available,
    coalesce(v_product.stock_quantity, v_product.inventory_qty, 0)), 0);
end;
$$;

revoke all on function public.online_product_available_quantity(uuid, uuid)
  from public, anon, authenticated, service_role;

create or replace function public.get_online_order_inventory_reservation_deadline(
  p_order_id uuid
)
returns timestamptz
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_tenant_id uuid;
  v_deadline timestamptz;
begin
  select orders.tenant_id into v_tenant_id
    from public.online_orders orders
   where orders.id = p_order_id;
  if not found then
    return null;
  end if;

  if coalesce(auth.role(), '') <> 'service_role'
     and (
       auth.uid() is null
       or public.user_tenant_id() is distinct from v_tenant_id
     ) then
    raise exception 'Order not found or access denied'
      using errcode = '42501';
  end if;

  select min(reservation.expires_at) into v_deadline
    from public.online_order_inventory_reservations reservation
   where reservation.tenant_id = v_tenant_id
     and reservation.order_id = p_order_id
     and reservation.state = 'active'
     and reservation.expires_at > clock_timestamp();

  return v_deadline;
end;
$$;

