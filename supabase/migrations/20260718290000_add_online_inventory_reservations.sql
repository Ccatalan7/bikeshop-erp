create or replace function public.prepare_online_inventory_reservation_consumption()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_non_posted constant text[] := array[
    'draft', 'borrador', 'sent', 'enviado', 'enviada',
    'issued', 'emitido', 'emitida',
    'cancelled', 'cancelado', 'cancelada', 'anulado', 'anulada'
  ];
  v_old_posted boolean := false;
  v_new_posted boolean;
  v_context_order_id uuid;
  v_order_id uuid;
  v_reservation public.online_order_inventory_reservations%rowtype;
begin
  v_new_posted := not (
    lower(coalesce(new.status, 'draft')) = any(v_non_posted)
  );
  if tg_op = 'UPDATE' then
    v_old_posted := not (
      lower(coalesce(old.status, 'draft')) = any(v_non_posted)
    );
  end if;
  if not v_new_posted or v_old_posted then
    return new;
  end if;

  begin
    v_context_order_id := nullif(
      current_setting('app.online_order_id', true),
      ''
    )::uuid;
  exception when invalid_text_representation then
    v_context_order_id := null;
  end;

  select orders.id into v_order_id
    from public.online_orders orders
   where orders.tenant_id = new.tenant_id
     and (
       (v_context_order_id is not null and orders.id = v_context_order_id)
       or orders.sales_invoice_id = new.id
     )
   order by (orders.id = v_context_order_id) desc
   limit 1
   for update;
  if not found then
    return new;
  end if;

  perform public.ensure_online_order_inventory_reservations(
    v_order_id,
    'sales_invoice_posting'
  );

  for v_reservation in
    update public.online_order_inventory_reservations reservation
       set state = 'consuming',
           consumption_started_at = clock_timestamp(),
           -- During BEFORE INSERT the invoice row does not exist yet, so an
           -- immediate FK cannot point at NEW.id. AFTER finalization binds the
           -- same id once the invoice and its stock movements are durable.
           sales_invoice_id = case
             when tg_op = 'INSERT' then reservation.sales_invoice_id
             else new.id
           end,
           version = reservation.version + 1,
           updated_at = clock_timestamp()
     where reservation.order_id = v_order_id
       and reservation.tenant_id = new.tenant_id
       and reservation.state = 'active'
       and reservation.expires_at > clock_timestamp()
     returning reservation.*
  loop
    perform public.append_online_inventory_reservation_event(
      v_reservation,
      'consumption_started',
      'active',
      'consuming',
      'sales_invoice_posting',
      'reservation-consume-start:' || v_reservation.id::text || ':'
        || new.id::text || ':' || v_reservation.cycle::text,
      jsonb_build_object('sales_invoice_id', new.id)
    );
  end loop;

  perform set_config(
    'app.online_order_reservation_order_id',
    v_order_id::text,
    true
  );
  return new;
end;
$$;

