as $$
  with policy as (
    select case lower(coalesce(
      nullif(btrim(coalesce((
        select setting.value
          from public.website_settings setting
         where setting.tenant_id = p_tenant_id
           and setting.key = 'product_visibility_stock_policy'
         limit 1
