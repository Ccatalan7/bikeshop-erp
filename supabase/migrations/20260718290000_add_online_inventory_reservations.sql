create or replace function public.finalize_online_inventory_reservations_for_invoice(
  p_order_id uuid,
  p_invoice_id uuid,
  p_tenant_id uuid,
  p_allow_deferred boolean default false
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_group record;
  v_moved integer;
  v_movement_ids uuid[];
  v_reservation public.online_order_inventory_reservations%rowtype;
begin
  if p_order_id is null or p_invoice_id is null or p_tenant_id is null then
    raise exception 'Order, invoice, and tenant are required to finalize reservations'
      using errcode = '22004';
  end if;

  -- A paid Mercado Pago event may insert the posted invoice from inside the
  -- online-order trigger stack. In that nested path the legacy invoice trigger
  -- deliberately defers its stock write until process_online_order_internal()
  -- resumes. Do not turn that valid sequencing into a false reconciliation
  -- failure; the public processor calls this same kernel strictly immediately
  -- after the stock movement is written. A partial movement is never deferred.
  if p_allow_deferred
     and exists (
       select 1
         from public.online_order_inventory_reservations reservation
        where reservation.tenant_id = p_tenant_id
          and reservation.order_id = p_order_id
          and reservation.state = 'consuming'
          and (
            reservation.sales_invoice_id = p_invoice_id
            or reservation.sales_invoice_id is null
          )
     )
     and not exists (
       select 1
         from public.stock_movements movement
        where movement.tenant_id = p_tenant_id
          and movement.reference = 'sales_invoice:' || p_invoice_id::text
          and movement.quantity < 0
          and exists (
            select 1
              from public.online_order_inventory_reservations reservation
             where reservation.tenant_id = p_tenant_id
               and reservation.order_id = p_order_id
               and reservation.state = 'consuming'
               and reservation.product_id = movement.product_id
          )
     ) then
    return false;
  end if;

  for v_group in
    select reservation.product_id,
           sum(reservation.quantity)::integer as required_quantity,
           array_agg(reservation.id order by reservation.id) as reservation_ids
      from public.online_order_inventory_reservations reservation
     where reservation.tenant_id = p_tenant_id
       and reservation.order_id = p_order_id
       and reservation.state = 'consuming'
       and (
         reservation.sales_invoice_id = p_invoice_id
         or reservation.sales_invoice_id is null
       )
     group by reservation.product_id
     order by reservation.product_id
  loop
    select coalesce(-sum(movement.quantity), 0)::integer,
           coalesce(array_agg(movement.id order by movement.id), array[]::uuid[])
      into v_moved, v_movement_ids
      from public.stock_movements movement
     where movement.tenant_id = p_tenant_id
       and movement.product_id = v_group.product_id
       and movement.reference = 'sales_invoice:' || p_invoice_id::text
       and movement.quantity < 0;

    if v_moved <> v_group.required_quantity then
      raise exception
        'Invoice stock movement does not reconcile to reservation for product %: expected %, moved %',
        v_group.product_id,
        v_group.required_quantity,
        v_moved
        using errcode = '23514';
    end if;

    for v_reservation in
      update public.online_order_inventory_reservations reservation
         set state = 'consumed',
             consumed_at = clock_timestamp(),
             sales_invoice_id = p_invoice_id,
             stock_movement_ids = v_movement_ids,
             version = reservation.version + 1,
             updated_at = clock_timestamp()
       where reservation.id = any(v_group.reservation_ids)
         and reservation.tenant_id = p_tenant_id
         and reservation.state = 'consuming'
       returning reservation.*
    loop
      perform public.append_online_inventory_reservation_event(
        v_reservation,
        'consumed',
        'consuming',
        'consumed',
        'sales_invoice_posting',
        'reservation-consumed:' || v_reservation.id::text || ':'
          || p_invoice_id::text || ':' || v_reservation.cycle::text,
        jsonb_build_object(
          'sales_invoice_id', p_invoice_id,
          'stock_movement_ids', to_jsonb(v_movement_ids)
        )
      );
    end loop;
  end loop;

  return true;
end;
$$;

