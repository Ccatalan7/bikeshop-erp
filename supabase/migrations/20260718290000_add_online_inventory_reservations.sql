create or replace view public.online_inventory_availability_view
with (security_invoker = true) as
select
  product.tenant_id,
  product.id as product_id,
  product.name as product_name,
  product.sku,
  coalesce(product.stock_quantity, product.inventory_qty, 0)::integer
    as physical_quantity,
  coalesce(reserved.quantity, 0)::integer as active_reserved_quantity,
  public.online_product_available_quantity(product.tenant_id, product.id)
    as available_quantity,
  coalesce(product.track_stock, true) as track_stock,
  coalesce(product.is_set, false) as is_set,
  product.updated_at
from public.products product
left join lateral (
  select coalesce(sum(reservation.quantity), 0)::integer as quantity
    from public.online_order_inventory_reservations reservation
   where reservation.tenant_id = product.tenant_id
     and reservation.product_id = product.id
     and reservation.state = 'active'
     and reservation.expires_at > clock_timestamp()
) reserved on true;

