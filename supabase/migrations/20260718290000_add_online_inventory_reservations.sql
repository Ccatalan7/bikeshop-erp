  perform public.finalize_online_inventory_reservations_for_invoice(
    p_order_id,
    v_invoice_id,
    v_tenant_id,
    false
  );
  perform set_config('app.online_order_id', coalesce(v_previous_context, ''), true);
  return v_invoice_id;
exception when others then
  perform set_config('app.online_order_id', coalesce(v_previous_context, ''), true);
  raise;
end;
$$;

