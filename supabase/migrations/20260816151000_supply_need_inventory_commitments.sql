create or replace function public.finalize_workshop_commitment_consumption_v1()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_non_posted constant text[] := array[
    'draft', 'borrador', 'sent', 'enviado', 'enviada',
    'issued', 'emitido', 'emitida',
    'cancelled', 'cancelado', 'cancelada', 'anulado', 'anulada'
  ];
  v_old_posted boolean := false;
  v_new_posted boolean;
  v_group record;
  v_moved integer;
  v_movement_ids uuid[];
  v_commitment public.workshop_inventory_commitments%rowtype;
  v_need public.supply_needs%rowtype;
  v_from_state text;
begin
  v_new_posted := not (lower(coalesce(new.status, 'draft')) = any(v_non_posted));
  if tg_op = 'UPDATE' then
    v_old_posted := not (
      lower(coalesce(old.status, 'draft')) = any(v_non_posted)
    );
  end if;

  if v_new_posted and not v_old_posted then
    for v_group in
      select commitment.product_id,
             sum(commitment.quantity)::integer as committed_quantity,
             array_agg(commitment.id order by commitment.id) as commitment_ids
      from public.workshop_inventory_commitments commitment
      where commitment.tenant_id = new.tenant_id
        and commitment.state = 'consuming'
        and (
          commitment.sales_invoice_id = new.id
          or commitment.sales_invoice_id is null
        )
      group by commitment.product_id
      order by commitment.product_id
    loop
      select greatest(coalesce(-sum(movement.quantity), 0), 0)::integer,
             coalesce(
               array_agg(movement.id order by movement.id)
                 filter (where movement.quantity < 0),
               array[]::uuid[]
             )
      into v_moved, v_movement_ids
      from public.stock_movements movement
      where movement.tenant_id = new.tenant_id
        and movement.product_id = v_group.product_id
        and movement.reference = 'sales_invoice:' || new.id::text;
      if v_moved < v_group.committed_quantity then
        raise exception
          'El movimiento de la factura no cubre el compromiso del taller para el producto %: compromiso %, movimiento %.',
          v_group.product_id, v_group.committed_quantity, v_moved
          using errcode = '23514';
      end if;

      for v_commitment in
        update public.workshop_inventory_commitments commitment
        set state = 'consumed',
            consumed_at = clock_timestamp(),
            sales_invoice_id = new.id,
            stock_movement_ids = v_movement_ids,
            version = commitment.version + 1,
            updated_by = auth.uid(),
            updated_at = clock_timestamp()
        where commitment.tenant_id = new.tenant_id
          and commitment.id = any(v_group.commitment_ids)
          and commitment.state = 'consuming'
        returning commitment.*
      loop
        perform public.append_workshop_inventory_commitment_event_v1(
          v_commitment, 'consumed', 'consuming', 'consumed',
          'sales_invoice_posting',
          'workshop-commitment-consumed:' || v_commitment.id::text || ':'
            || new.id::text || ':' || v_commitment.cycle::text,
          jsonb_build_object(
            'sales_invoice_id', new.id,
            'stock_movement_ids', to_jsonb(v_movement_ids)
          )
        );
      end loop;
    end loop;

    for v_need in
      update public.supply_needs need
      set supply_state = 'covered',
          version = need.version + 1,
          updated_by = auth.uid(),
          updated_at = clock_timestamp()
      where need.tenant_id = new.tenant_id
        and need.supply_state = 'committed'
        and exists (
          select 1 from public.workshop_inventory_commitments commitment
          where commitment.tenant_id = need.tenant_id
            and commitment.supply_need_id = need.id
            and commitment.state = 'consumed'
            and commitment.sales_invoice_id = new.id
        )
        and not exists (
          select 1 from public.workshop_inventory_commitments commitment
          where commitment.tenant_id = need.tenant_id
            and commitment.supply_need_id = need.id
            and commitment.state in ('active', 'consuming')
        )
      returning need.*
    loop
      insert into public.supply_need_events (
        tenant_id, supply_need_id, action, changed, actor_id, operation_key,
        request_snapshot, response_snapshot, occurred_at
      ) values (
        v_need.tenant_id, v_need.id, 'covered', true, auth.uid(),
        'workshop-invoice-covered:' || new.id::text || ':' || v_need.id::text,
        jsonb_build_object('sales_invoice_id', new.id),
        jsonb_build_object(
          'need_id', v_need.id,
          'changed', true,
          'version', v_need.version,
          'need', to_jsonb(v_need)
        ),
        clock_timestamp()
      ) on conflict (tenant_id, operation_key) do nothing;
    end loop;
  elsif not v_new_posted and v_old_posted then
    perform pg_advisory_xact_lock(hashtextextended(
      'online_inventory_reservation:' || new.tenant_id::text,
      0
    ));
    for v_commitment in
      update public.workshop_inventory_commitments commitment
      set state = 'active',
          cycle = commitment.cycle + 1,
          version = commitment.version + 1,
          assigned_at = clock_timestamp(),
          review_due_at = clock_timestamp() + interval '30 days',
          consumption_started_at = null,
          consumed_at = null,
          sales_invoice_id = null,
          stock_movement_ids = array[]::uuid[],
          updated_by = auth.uid(),
          updated_at = clock_timestamp()
      where commitment.tenant_id = new.tenant_id
        and commitment.sales_invoice_id = new.id
        and commitment.state = 'consumed'
      returning commitment.*
    loop
      perform public.append_workshop_inventory_commitment_event_v1(
        v_commitment, 'reactivated', 'consumed', 'active',
        'sales_invoice_reopened',
        'workshop-commitment-reactivated:' || v_commitment.id::text || ':'
          || new.id::text || ':' || v_commitment.cycle::text,
        jsonb_build_object('sales_invoice_id', new.id)
      );
    end loop;

    for v_need in
      update public.supply_needs need
      set supply_state = 'committed',
          version = need.version + 1,
          updated_by = auth.uid(),
          updated_at = clock_timestamp()
      where need.tenant_id = new.tenant_id
        and need.supply_state = 'covered'
        and exists (
          select 1 from public.workshop_inventory_commitments commitment
          where commitment.tenant_id = need.tenant_id
            and commitment.supply_need_id = need.id
            and commitment.state = 'active'
        )
      returning need.*
    loop
      insert into public.supply_need_events (
        tenant_id, supply_need_id, action, changed, actor_id, operation_key,
        request_snapshot, response_snapshot, occurred_at
      ) values (
        v_need.tenant_id, v_need.id, 'stock_reactivated', true, auth.uid(),
        'workshop-invoice-reactivated:' || new.id::text || ':' || v_need.id::text,
        jsonb_build_object('sales_invoice_id', new.id),
        jsonb_build_object(
          'need_id', v_need.id,
          'changed', true,
          'version', v_need.version,
          'need', to_jsonb(v_need)
        ),
        clock_timestamp()
      ) on conflict (tenant_id, operation_key) do nothing;
    end loop;
  end if;
  return new;
end;
$$;

