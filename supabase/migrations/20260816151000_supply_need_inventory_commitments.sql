    select requirement.product_id, requirement.required_quantity
    from (
      select v_source.id as product_id,
             v_need.quantity::integer as required_quantity
      where not coalesce(v_source.is_set, false)
      union all
      select map.component_product_id,
             (v_need.quantity::integer * map.quantity_in_set)::integer
      from public.product_set_components map
      where map.tenant_id = v_tenant_id
        and map.set_product_id = v_source.id
        and coalesce(v_source.is_set, false)
    ) requirement
    order by requirement.product_id
  loop
    v_target_count := v_target_count + 1;
    select product.* into v_target_product
    from public.products product
    where product.tenant_id = v_tenant_id
      and product.id = v_target.product_id
      and product.is_active is true
    for update;
    if not found then
      raise exception 'Un componente físico no existe o está inactivo.'
        using errcode = '23514';
    end if;

    select commitment.* into v_existing
    from public.workshop_inventory_commitments commitment
    where commitment.tenant_id = v_tenant_id
      and commitment.supply_need_id = v_need.id
      and commitment.product_id = v_target.product_id
    for update;
    v_was_existing := found;
    if v_was_existing and v_existing.state in ('active', 'consuming', 'consumed') then
      raise exception 'La necesidad ya conserva un compromiso vigente o consumido.'
        using errcode = '55000';
    end if;

    v_capacity := public.assert_inventory_commitment_capacity_v1(
      v_tenant_id,
      v_target.product_id,
      v_target.required_quantity,
      null,
      case when v_was_existing then v_existing.id else null end
    );

    if v_was_existing then
      update public.workshop_inventory_commitments commitment
      set source_product_id = v_source.id,
          quantity = v_target.required_quantity,
          state = 'active',
          cycle = commitment.cycle + 1,
          version = commitment.version + 1,
          assigned_at = clock_timestamp(),
          review_due_at = clock_timestamp() + interval '30 days',
          consumption_started_at = null,
          consumed_at = null,
          released_at = null,
          release_reason = null,
          sales_invoice_id = null,
          stock_movement_ids = array[]::uuid[],
          updated_by = v_actor_id,
          updated_at = clock_timestamp()
      where commitment.tenant_id = v_tenant_id
        and commitment.id = v_existing.id
      returning commitment.* into v_commitment;
    else
      insert into public.workshop_inventory_commitments (
        tenant_id, supply_need_id, source_product_id, product_id, quantity,
        state, assigned_at, review_due_at, created_by, updated_by
      ) values (
        v_tenant_id, v_need.id, v_source.id, v_target.product_id,
        v_target.required_quantity, 'active', clock_timestamp(),
        clock_timestamp() + interval '30 days', v_actor_id, v_actor_id
      ) returning * into v_commitment;
    end if;

    perform public.append_workshop_inventory_commitment_event_v1(
      v_commitment,
      case when v_was_existing then 'reassigned' else 'assigned' end,
      case when v_was_existing then v_existing.state else null end,
      'active',
      'supply_need_command',
      'workshop-commitment-assigned:' || v_commitment.id::text || ':'
        || v_commitment.cycle::text,
      v_capacity || jsonb_build_object('source_product_id', v_source.id)
    );
    v_components := v_components || jsonb_build_array(jsonb_build_object(
      'commitment_id', v_commitment.id,
      'product_id', v_commitment.product_id,
      'quantity', v_commitment.quantity,
      'capacity', v_capacity
    ));
  end loop;

  if v_target_count = 0 then
    raise exception 'No se pudo resolver ningún componente físico.'
      using errcode = '23514';
  end if;

  update public.supply_needs need
  set supply_state = 'committed',
      version = need.version + 1,
      internal_stock_rejection_reason = null,
      internal_stock_rejected_at = null,
      internal_stock_rejected_by = null,
      updated_by = v_actor_id,
      updated_at = clock_timestamp()
  where need.tenant_id = v_tenant_id and need.id = v_need.id
  returning * into v_need;

  v_response := jsonb_build_object(
    'need_id', v_need.id,
    'changed', true,
    'version', v_need.version,
    'need', to_jsonb(v_need),
    'commitments', v_components
  );
  insert into public.supply_need_events (
    tenant_id, supply_need_id, action, changed, actor_id, operation_key,
    request_snapshot, response_snapshot, occurred_at
  ) values (
    v_tenant_id, v_need.id, 'stock_assigned', true, v_actor_id,
    v_operation_key, v_request, v_response, clock_timestamp()
  ) returning * into v_receipt;

  return to_jsonb(v_receipt) || v_response
    || jsonb_build_object('replay', false);
end;
