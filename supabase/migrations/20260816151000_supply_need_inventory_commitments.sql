create or replace function public.guard_reserved_product_set_components()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tenant_id uuid := coalesce(new.tenant_id, old.tenant_id);
  v_set_product_id uuid := coalesce(new.set_product_id, old.set_product_id);
begin
  if exists (
    select 1
    from public.online_order_inventory_reservations reservation
    join public.online_order_items item
      on item.id = reservation.order_item_id
     and item.tenant_id = reservation.tenant_id
    where reservation.tenant_id = v_tenant_id
      and item.product_id = v_set_product_id
      and reservation.state in ('active', 'consuming')
      and (
        reservation.state = 'consuming'
        or reservation.expires_at > clock_timestamp()
      )
  ) or exists (
    select 1 from public.workshop_inventory_commitments commitment
    where commitment.tenant_id = v_tenant_id
      and commitment.source_product_id = v_set_product_id
      and commitment.state in ('active', 'consuming')
  ) then
    raise exception
      'Los componentes del set están bloqueados por un compromiso de inventario.'
      using errcode = '23514';
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

