create or replace function public.append_workshop_inventory_commitment_event_v1(
  p_commitment public.workshop_inventory_commitments,
  p_event_type text,
  p_from_state text,
  p_to_state text,
  p_executor text,
  p_operation_key text,
  p_payload jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  if p_commitment.id is null
     or btrim(coalesce(p_executor, '')) = ''
     or btrim(coalesce(p_operation_key, '')) = '' then
    raise exception 'La identidad del evento de compromiso es obligatoria.'
      using errcode = '22023';
  end if;

  insert into public.workshop_inventory_commitment_events (
    tenant_id, commitment_id, supply_need_id, source_product_id, product_id,
    event_type, from_state, to_state, quantity, cycle, actor_id, executor,
    operation_key, payload, occurred_at
  ) values (
    p_commitment.tenant_id, p_commitment.id, p_commitment.supply_need_id,
    p_commitment.source_product_id, p_commitment.product_id,
    p_event_type, p_from_state, p_to_state, p_commitment.quantity,
    p_commitment.cycle, auth.uid(), btrim(p_executor),
    btrim(p_operation_key), coalesce(p_payload, '{}'::jsonb), clock_timestamp()
  ) on conflict (tenant_id, operation_key) do nothing
  returning id into v_id;

  if v_id is null then
    select event.id into v_id
    from public.workshop_inventory_commitment_events event
    where event.tenant_id = p_commitment.tenant_id
      and event.operation_key = btrim(p_operation_key)
      and event.commitment_id = p_commitment.id
      and event.event_type = p_event_type;
    if not found then
      raise exception 'La clave del evento pertenece a otro compromiso.'
        using errcode = '23505';
    end if;
  end if;
  return v_id;
end;
$$;

