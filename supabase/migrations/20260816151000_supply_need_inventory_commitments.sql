    raise exception 'El stock inventariable se asigna en unidades enteras.'
      using errcode = '23514';
  end if;

  select product.* into v_source
  from public.products product
  where product.tenant_id = v_tenant_id
    and product.id = v_need.product_id
    and product.is_active is true
  for share;
  if not found
     or coalesce(v_source.is_service, false)
     or coalesce(v_source.product_type, 'product') = 'service'
     or not coalesce(v_source.track_stock, true)
     or coalesce(v_source.purchase_treatment, 'inventory') <> 'inventory' then
    raise exception 'El producto confirmado no es inventariable.'
      using errcode = '23514';
  end if;
  if coalesce(v_source.is_set, false) and not exists (
    select 1 from public.product_set_components map
    where map.tenant_id = v_tenant_id and map.set_product_id = v_source.id
  ) then
    raise exception 'El set confirmado no tiene componentes canónicos.'
      using errcode = '23514';
  end if;

