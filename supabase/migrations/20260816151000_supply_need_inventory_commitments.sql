create or replace view public.inventory_availability_v1
with (security_invoker = true)
as
select
  product.tenant_id,
  product.id as product_id,
  product.name as product_name,
  product.sku,
  coalesce(product.stock_quantity, product.inventory_qty, 0)::integer
    as physical_quantity,
  coalesce(online.quantity, 0)::integer as online_committed_quantity,
  coalesce(workshop.quantity, 0)::integer as workshop_committed_quantity,
  (
    coalesce(online.quantity, 0) + coalesce(workshop.quantity, 0)
  )::integer as total_committed_quantity,
  public.inventory_available_quantity_v1(product.tenant_id, product.id)
    as available_to_promise,
  coalesce(product.track_stock, true) as track_stock,
  coalesce(product.is_set, false) as is_set,
  product.updated_at
from public.products product
left join lateral (
  select coalesce(sum(reservation.quantity), 0)::integer as quantity
  from public.online_order_inventory_reservations reservation
  where reservation.tenant_id = product.tenant_id
    and reservation.product_id = product.id
    and reservation.state = 'active'
    and reservation.expires_at > clock_timestamp()
) online on true
left join lateral (
  select coalesce(sum(commitment.quantity), 0)::integer as quantity
  from public.workshop_inventory_commitments commitment
  where commitment.tenant_id = product.tenant_id
    and commitment.product_id = product.id
    and commitment.state = 'active'
) workshop on true;

