create or replace function public.prepare_workshop_commitment_consumption_v1()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_non_posted constant text[] := array[
    'draft', 'borrador', 'sent', 'enviado', 'enviada',
    'issued', 'emitido', 'emitida',
    'cancelled', 'cancelado', 'cancelada', 'anulado', 'anulada'
  ];
  v_old_posted boolean := false;
  v_new_posted boolean;
  v_job public.mechanic_jobs%rowtype;
  v_group record;
  v_invoice_quantity integer;
  v_commitment public.workshop_inventory_commitments%rowtype;
begin
  v_new_posted := not (lower(coalesce(new.status, 'draft')) = any(v_non_posted));
  if tg_op = 'UPDATE' then
    v_old_posted := not (
      lower(coalesce(old.status, 'draft')) = any(v_non_posted)
    );
  end if;

  if tg_op = 'UPDATE' and v_old_posted and v_new_posted
     and public.invoice_inventory_signature(old.items)
         is distinct from public.invoice_inventory_signature(new.items)
     and exists (
       select 1 from public.workshop_inventory_commitments commitment
       where commitment.tenant_id = new.tenant_id
         and commitment.sales_invoice_id = new.id
         and commitment.state = 'consumed'
     ) then
    raise exception
      'La factura consumió stock comprometido del taller. Vuelve a borrador antes de editar sus productos.'
      using errcode = '55000';
  end if;

  if not v_new_posted or v_old_posted then
    return new;
  end if;

  select job.* into v_job
  from public.mechanic_jobs job
  where job.tenant_id = new.tenant_id
    and job.invoice_id = new.id
    and job.deleted_at is null
  order by job.created_at, job.id
  limit 1
  for update;
  if not found then
    return new;
  end if;

  perform pg_advisory_xact_lock(hashtextextended(
    'online_inventory_reservation:' || new.tenant_id::text,
    0
  ));

  for v_group in
    select commitment.product_id,
           sum(commitment.quantity)::integer as committed_quantity
    from public.workshop_inventory_commitments commitment
    join public.supply_needs need
      on need.tenant_id = commitment.tenant_id
     and need.id = commitment.supply_need_id
    where commitment.tenant_id = new.tenant_id
      and need.mechanic_job_id = v_job.id
      and commitment.state = 'active'
    group by commitment.product_id
    order by commitment.product_id
  loop
    select coalesce(requirement.quantity, 0)::integer into v_invoice_quantity
    from public.sales_invoice_stock_requirements(new.tenant_id, new.items)
      requirement
    where requirement.product_id = v_group.product_id;
    v_invoice_quantity := coalesce(v_invoice_quantity, 0);
    if v_invoice_quantity = 0 then
      continue;
    end if;
    if v_invoice_quantity < v_group.committed_quantity then
      raise exception
        'La factura incluye menos unidades que el compromiso del taller para el producto %: factura %, compromiso %.',
        v_group.product_id, v_invoice_quantity, v_group.committed_quantity
        using errcode = '23514';
    end if;

    for v_commitment in
      update public.workshop_inventory_commitments commitment
      set state = 'consuming',
          consumption_started_at = clock_timestamp(),
          sales_invoice_id = case
            when tg_op = 'INSERT' then commitment.sales_invoice_id
            else new.id
          end,
          version = commitment.version + 1,
          updated_by = auth.uid(),
          updated_at = clock_timestamp()
      from public.supply_needs need
      where need.tenant_id = commitment.tenant_id
        and need.id = commitment.supply_need_id
        and commitment.tenant_id = new.tenant_id
        and need.mechanic_job_id = v_job.id
        and commitment.product_id = v_group.product_id
        and commitment.state = 'active'
      returning commitment.*
    loop
      perform public.append_workshop_inventory_commitment_event_v1(
        v_commitment, 'consumption_started', 'active', 'consuming',
        'sales_invoice_posting',
        'workshop-commitment-consume-start:' || v_commitment.id::text || ':'
          || new.id::text || ':' || v_commitment.cycle::text,
        jsonb_build_object('sales_invoice_id', new.id)
      );
    end loop;
  end loop;
  return new;
end;
$$;

