-- Every physical consumer now protects the union of online and workshop
-- commitments. The established negative-stock policy remains unchanged when
-- that protected floor is zero.
create or replace function public.guard_product_reserved_inventory_balance()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_committed integer;
  v_online integer;
  v_workshop integer;
  v_new_stock integer;
begin
  select coalesce(sum(reservation.quantity), 0)::integer into v_online
  from public.online_order_inventory_reservations reservation
  where reservation.tenant_id = old.tenant_id
    and reservation.product_id = old.id
    and reservation.state = 'active'
    and reservation.expires_at > clock_timestamp();
  select coalesce(sum(commitment.quantity), 0)::integer into v_workshop
  from public.workshop_inventory_commitments commitment
  where commitment.tenant_id = old.tenant_id
    and commitment.product_id = old.id
    and commitment.state = 'active';
  v_committed := v_online + v_workshop;

  v_new_stock := least(
    coalesce(new.inventory_qty, 0),
    coalesce(new.stock_quantity, 0)
  );
  if v_committed > 0 and v_new_stock < v_committed then
    if v_workshop = 0 then
      -- Preserve the established online-only error contract byte-for-byte.
      raise exception
        'Stock update would consume % units reserved for online orders; available floor is %',
        v_online, v_online using errcode = '23514';
    end if;
    raise exception
      'La actualización consumiría unidades comprometidas; el piso protegido es %.',
      v_committed using errcode = '23514';
  end if;
  return new;
end;
$$;

revoke all on function public.guard_product_reserved_inventory_balance()
  from public, anon, authenticated, service_role;

create or replace function public.guard_reserved_product_classification()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if row(
    old.track_stock, old.is_service, old.product_type,
    old.purchase_treatment, old.is_set
  ) is distinct from row(
    new.track_stock, new.is_service, new.product_type,
    new.purchase_treatment, new.is_set
  ) and (
    exists (
      select 1
      from public.online_order_inventory_reservations reservation
      join public.online_order_items item
        on item.id = reservation.order_item_id
       and item.tenant_id = reservation.tenant_id
      where reservation.tenant_id = old.tenant_id
        and reservation.state in ('active', 'consuming')
        and (
          reservation.state = 'consuming'
          or reservation.expires_at > clock_timestamp()
        )
        and (reservation.product_id = old.id or item.product_id = old.id)
    )
    or exists (
      select 1 from public.workshop_inventory_commitments commitment
      where commitment.tenant_id = old.tenant_id
        and commitment.state in ('active', 'consuming')
        and (
          commitment.product_id = old.id
          or commitment.source_product_id = old.id
        )
    )
  ) then
    raise exception
      'La clasificación del producto está bloqueada por un compromiso de inventario.'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

