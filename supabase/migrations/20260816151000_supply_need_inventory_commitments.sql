create or replace function public.inventory_available_quantity_v1(
  p_tenant_id uuid,
  p_product_id uuid
)
returns integer
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_product public.products%rowtype;
  v_available integer;
begin
  select product.* into v_product
  from public.products product
  where product.tenant_id = p_tenant_id and product.id = p_product_id;
  if not found then
    return 0;
  end if;

  if coalesce(v_product.is_service, false)
     or coalesce(v_product.product_type, 'product') = 'service'
     or not coalesce(v_product.track_stock, true) then
    return greatest(
      coalesce(v_product.stock_quantity, v_product.inventory_qty, 0), 0
    );
  end if;

  if coalesce(v_product.is_set, false) then
    select min(greatest(floor(
      (
        coalesce(component.stock_quantity, component.inventory_qty, 0)
        - coalesce(committed.quantity, 0)
      )::numeric / set_component.quantity_in_set
    ), 0))::integer
    into v_available
    from public.product_set_components set_component
    join public.products component
      on component.tenant_id = set_component.tenant_id
     and component.id = set_component.component_product_id
    left join lateral (
      select coalesce(sum(active.quantity), 0)::integer as quantity
      from public.active_inventory_commitments_v1 active
      where active.tenant_id = component.tenant_id
        and active.product_id = component.id
    ) committed on true
    where set_component.tenant_id = p_tenant_id
      and set_component.set_product_id = p_product_id;
    return greatest(coalesce(v_available, 0), 0);
  end if;

  select greatest(
    coalesce(v_product.stock_quantity, v_product.inventory_qty, 0)
      - coalesce(sum(active.quantity), 0),
    0
  )::integer
  into v_available
  from public.active_inventory_commitments_v1 active
  where active.tenant_id = p_tenant_id
    and active.product_id = p_product_id;

  return greatest(coalesce(
    v_available,
    coalesce(v_product.stock_quantity, v_product.inventory_qty, 0)
  ), 0);
end;
$$;

revoke all on function public.inventory_available_quantity_v1(uuid, uuid)
  from public, anon, authenticated, service_role;

