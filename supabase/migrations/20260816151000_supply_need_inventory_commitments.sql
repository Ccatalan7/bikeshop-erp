create or replace function public.assert_inventory_commitment_capacity_v1(
  p_tenant_id uuid,
  p_product_id uuid,
  p_quantity integer,
  p_exclude_online_id uuid default null,
  p_exclude_workshop_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
set lock_timeout = '750ms'
as $$
declare
  v_product public.products%rowtype;
  v_online integer;
  v_workshop integer;
  v_physical integer;
  v_available integer;
begin
  if p_tenant_id is null or p_product_id is null
     or p_quantity is null or p_quantity <= 0 then
    raise exception 'El producto, tenant y cantidad del compromiso son obligatorios.'
      using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(
    'online_inventory_reservation:' || p_tenant_id::text,
    0
  ));

  select product.* into v_product
  from public.products product
  where product.tenant_id = p_tenant_id and product.id = p_product_id
  for update;
  if not found then
    raise exception 'Producto físico no encontrado.' using errcode = 'P0002';
  end if;
  if coalesce(v_product.is_set, false)
     or coalesce(v_product.is_service, false)
     or coalesce(v_product.product_type, 'product') = 'service'
     or not coalesce(v_product.track_stock, true)
     or coalesce(v_product.purchase_treatment, 'inventory') <> 'inventory' then
    raise exception 'El compromiso requiere un producto físico inventariable.'
      using errcode = '23514';
  end if;
  if coalesce(v_product.inventory_qty, 0)
     <> coalesce(v_product.stock_quantity, 0) then
    raise exception 'Las columnas de stock no coinciden para %.', v_product.name
      using errcode = '23514';
  end if;

  select coalesce(sum(reservation.quantity), 0)::integer into v_online
  from public.online_order_inventory_reservations reservation
  where reservation.tenant_id = p_tenant_id
    and reservation.product_id = p_product_id
    and reservation.state = 'active'
    and reservation.expires_at > clock_timestamp()
    and (p_exclude_online_id is null or reservation.id <> p_exclude_online_id);

  select coalesce(sum(commitment.quantity), 0)::integer into v_workshop
  from public.workshop_inventory_commitments commitment
  where commitment.tenant_id = p_tenant_id
    and commitment.product_id = p_product_id
    and commitment.state = 'active'
    and (
      p_exclude_workshop_id is null
      or commitment.id <> p_exclude_workshop_id
    );

  v_physical := coalesce(
    v_product.stock_quantity, v_product.inventory_qty, 0
  );
  v_available := v_physical - v_online - v_workshop;
  if v_available < p_quantity then
    raise exception
      'Stock disponible insuficiente para %: solicitado %, ATP %.',
      v_product.name, p_quantity, greatest(v_available, 0)
      using errcode = '23514';
  end if;

  return jsonb_build_object(
    'product_id', v_product.id,
    'on_hand', v_physical,
    'online_committed', v_online,
    'workshop_committed', v_workshop,
    'atp_before', greatest(v_available, 0),
    'atp_after', greatest(v_available - p_quantity, 0)
  );
end;
$$;

revoke all on function public.assert_inventory_commitment_capacity_v1(
  uuid, uuid, integer, uuid, uuid
) from public, anon, authenticated, service_role;

create or replace function public.guard_online_inventory_common_capacity_v1()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.state = 'active' and new.expires_at > clock_timestamp()
     and (
       tg_op = 'INSERT'
       or old.state is distinct from new.state
       or old.quantity is distinct from new.quantity
       or old.product_id is distinct from new.product_id
       or old.expires_at is distinct from new.expires_at
     ) then
    perform public.assert_inventory_commitment_capacity_v1(
      new.tenant_id,
      new.product_id,
      new.quantity,
      case when tg_op = 'UPDATE' then old.id else null end,
      null
    );
  end if;
  return new;
end;
$$;

