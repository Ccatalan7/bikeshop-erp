--
-- Purpose:
--   Add workshop stock commitments without replacing the proven online-order
--   reservation lifecycle. Both ledgers feed one ATP authority, share the same
--   tenant advisory lock, and are protected by one capacity check. A workshop
--   commitment never changes physical stock; a linked posted sales invoice
--   remains the sole owner of inventory movements and atomically consumes the
--   commitment that belongs to its job.
--
-- Forward behavior:
--   Additive workshop ledger/read models/commands plus compatible replacements
--   of the existing availability and reservation-floor functions. The public
--   catalog and set availability keep their signatures and inherit common ATP.
-- Recovery behavior:
--   Disable workshop assignment entry points while preserving commitment and
--   event evidence. Replacing online_product_available_quantity with its prior
--   body restores online-only reads without deleting workshop rows.

