create table if not exists public.workshop_inventory_commitments (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants(id) on delete restrict,
  supply_need_id uuid not null,
  source_product_id uuid not null,
  product_id uuid not null,
  quantity integer not null check (quantity > 0),
  state text not null default 'active' check (
    state in ('active', 'consuming', 'consumed', 'released')
  ),
  cycle integer not null default 1 check (cycle > 0),
  version bigint not null default 1 check (version > 0),
  assigned_at timestamptz not null default clock_timestamp(),
  review_due_at timestamptz not null default (
    clock_timestamp() + interval '30 days'
  ),
  consumption_started_at timestamptz,
  consumed_at timestamptz,
  released_at timestamptz,
  release_reason text,
  sales_invoice_id uuid references public.sales_invoices(id) on delete restrict,
  stock_movement_ids uuid[] not null default array[]::uuid[],
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default clock_timestamp(),
  unique (tenant_id, id),
  unique (tenant_id, supply_need_id, product_id),
  foreign key (tenant_id, supply_need_id)
    references public.supply_needs(tenant_id, id) on delete restrict,
  foreign key (tenant_id, source_product_id)
    references public.products(tenant_id, id) on delete restrict,
  foreign key (tenant_id, product_id)
    references public.products(tenant_id, id) on delete restrict,
  check (state <> 'consuming' or consumption_started_at is not null),
  check (state <> 'consumed' or consumed_at is not null),
  check (
    state <> 'released'
    or (released_at is not null and btrim(coalesce(release_reason, '')) <> '')
  )
);

